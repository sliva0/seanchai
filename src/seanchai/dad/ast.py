class InterpretedConstraints(Node):
    """`; Type: Interpreted Constraints`: what a clause's prose says of one
    AVP's value or presence, as a person read it, each rule after the
    sentences it was read from.

    `avp` is the AVP the rules constrain. `command` (with `application_id`
    where the document prints the command for several applications, and
    `command_section`, the clause of its block, where it prints the command
    more than once for one application or for none) or `within`, a grouped
    AVP, scopes them to where the AVP appears there, and is where a
    predicate's conditions are looked up; with neither, the rules hold
    wherever the document reads the AVP. `table` names the table
    printing the quote, an information element's description. `versions` is
    the range of document versions the quotes were checked against.

    Only the document's interpretations file writes the block
    (`InterpretationBlock`, merged in as the corrections are applied), so
    only a corrected file holds one, and the format marks it interpreted:
    nothing in it is structure the document prints.
    """

    type: Literal["Interpreted Constraints"] = "Interpreted Constraints"
    avp: AvpName
    command: AvpName | None = None
    application_id: Unsigned32 | None = None
    command_section: SectionNumber | None = None
    within: AvpName | None = None
    table: TableLabel | None = None
    source: SourceRef
    versions: VersionsText
    # Quotes and rules, in reading order: each run of quotes is followed by
    # the rules read from it.
    body: Annotated[tuple[Quote | ConstraintRule, ...], Field(min_length=2)]

    @pydantic.model_validator(mode="after")
    def _shape(self) -> InterpretedConstraints:
        if self.command is not None and self.within is not None:
            raise ValueError("a block is scoped to a command or a grouped AVP")
        if self.application_id is not None and self.command is None:
            raise ValueError("Application-ID chooses among a command's applications")
        if self.command_section is not None and self.command is None:
            raise ValueError("Command-Section chooses among a command's prints")
        if not isinstance(self.body[0], Quote):
            raise ValueError("the body opens with the quote its rules are read from")
        if isinstance(self.body[-1], Quote):
            raise ValueError("a quote is followed by the rules read from it")
        for reading in self.readings:
            if len(reading.rules) > 1 and any(
                isinstance(rule, TextOnly) for rule in reading.rules
            ):
                raise ValueError("text-only is a reading's only rule")
        if self.within is None and any(
            isinstance(rule, UniqueRule) for rule in self.body
        ):
            raise ValueError("unique holds among the grouped AVPs Within names")
        return self

    @property
    def readings(self) -> tuple[Reading, ...]:
        """The body as quotes and the rules read from them."""
        readings: list[Reading] = []
        quotes: list[str] = []
        rules: list[Any] = []
        for item in self.body:
            if isinstance(item, Quote):
                if rules:
                    readings.append(Reading(quotes=tuple(quotes), rules=tuple(rules)))
                    quotes, rules = [], []
                quotes.append(item.text)
            else:
                rules.append(item)
        if quotes and rules:
            readings.append(Reading(quotes=tuple(quotes), rules=tuple(rules)))
        return tuple(readings)


_ID_PATTERN = r"^[a-z0-9]+(-[a-z0-9]+)*$"


class InterpretationBlock(InterpretedConstraints):
    """An Interpreted Constraints block as a `.dadx` file writes it by hand:
    `id`, its `; Id:` line, names it where the corrected file's note cites it
    (`TS29.272.dadx#imei-digits`) and the corrections record keys it. No
    page: a copy's page is read from its source as the block is merged."""

    id: Annotated[str, Field(pattern=_ID_PATTERN)]

    @pydantic.model_validator(mode="after")
    def _unpaged(self) -> InterpretationBlock:
        if self.source.page is not None:
            raise ValueError("a page is read from each copy's source, not written")
        return self

    @property
    def merged(self) -> InterpretedConstraints:
        """The block as a corrected file prints it, without its id."""
        values = {
            name: getattr(self, name) for name in InterpretedConstraints.model_fields
        }
        return InterpretedConstraints(**values)


class Interpretations(Node):
    """One `.dadx` file: what a person read in one document's prose, its
    `; Interprets:` header naming the document as `; Specification:` does,
    then its blocks in the document's clause order."""

    interprets: InlineText  # "3GPP TS 29.272"
    sections: tuple[InterpretationBlock, ...]

    @pydantic.model_validator(mode="after")
    def _unique_ids(self) -> Interpretations:
        seen: set[str] = set()
        for each in self.sections:
            if each.id in seen:
                raise ValueError(f"the id {each.id!r} names two blocks")
            seen.add(each.id)
        return self


def node_at(root: Node, path: TreePath) -> Any:
    """What `path` names under `root`: a node, or a field's value."""
    found: Any = root
    for step in path:
        found = found[step] if isinstance(step, int) else getattr(found, step)
    return found


