class ReusedColumn(enum.StrEnum):
    """The structural columns of a re-used AVPs table. Any other column is a
    mark column (`MarkColumn`)."""

    NAME = "Name"
    FROM = "From"
    M_BIT = "M-bit"
    # TS 29.172 table 7.4.1-2 and TS 32.299's tables 7.3.1-7.5.1 print the
    # code, 29.172 the type too, of the AVPs they re-use.
    CODE = "Code"
    TYPE = "Type"


REUSED_COLUMNS: tuple[ReusedColumn, ...] = (
    ReusedColumn.NAME,
    ReusedColumn.FROM,
    ReusedColumn.M_BIT,
)

# What a mark column may be called: a token, so `; Columns:` stays a list
# split at spaces.
MARK_COLUMN_PATTERN = r"[A-Za-z0-9][A-Za-z0-9_.-]*"
_STRUCTURAL_COLUMNS = frozenset(
    column.value for kind in (AvpColumn, ReusedColumn) for column in kind
)


def _not_structural(name: str) -> str:
    if name in _STRUCTURAL_COLUMNS:
        raise ValueError(f"{name!r} is a structural column, not a mark column")
    return name


# A column in which a table marks where its row applies, each cell a list of
# the document's marks. Both table kinds may carry them, and the set is open:
# a `; Columns:` entry that is no structural column of its table kind, nor of
# the other, is a mark column, named by the label its document prints in
# token form. What a mark means is the document's legend's to say, so the
# cells keep its spelling and consumers interpret them per column. The corpus
# holds:
#
# - `Acc-Type`: TS 29.212's and 29.215's "Acc. Type", the IP-CAN access types
#   the AVP applies to (`All`, `3GPP-EPS`, `Non-3GPP-EPS`, ...).
# - `Applicability`: the supported features an AVP belongs to ("AVPs marked
#   with a supported feature are applicable as described in clause 5.4.1",
#   TS 29.212 table 5.3.0.1 note 9; TS 29.468's `V2X Localized User Plane`),
#   and in TS 29.212 and 29.215 also the function: `CC` charging control,
#   `PC` policy control, `Both`, `ADC`, `ABC` (note 3).
# - `Reference-Points`: TS 29.061's "Applicable Reference Points" (`Gi`,
#   `Sgi`).
# - `ACR`, `ACA`, `CCR`, `CCA`: TS 32.299's "Used in" columns, one per
#   command: `M`, `OM` or `OC` (table 7.1.0.1, clause 7.1.0) or `X` (tables
#   7.2.0.1 and 7.3.1-7.5.1) where the AVP is used in it, a dash where it is
#   not.
# - `SI`, `CCR-MSCC`, `CCA-MSCC`: OMA-DDS-Charging_Data table 11's "Used In"
#   columns for the Service-Information AVP and for the
#   Multiple-Services-Credit-Control AVP in each command, beside its `ACR` to
#   `CCA`.
MarkColumn = Annotated[
    str,
    Field(pattern=f"^{MARK_COLUMN_PATTERN}$"),
    pydantic.AfterValidator(_not_structural),
]

# A table column: a structural one first, so that `Name` is never read as a
# mark column of that name.
AvpTableColumn = Annotated[AvpColumn | MarkColumn, Field(union_mode="left_to_right")]
ReusedTableColumn = Annotated[
    ReusedColumn | MarkColumn, Field(union_mode="left_to_right")
]


def mark_column(column: str) -> str | None:
    """`column` where it is a mark column, or None for a structural one."""
    return None if isinstance(column, AvpColumn | ReusedColumn) else column


def _check_columns(columns: Sequence[str]) -> None:
    """Check `; Columns:`, the modelled source columns in source order.
    Unmodelled columns are dropped; docs/extractor.md says why."""
    labels = [str(column) for column in columns]
    if len(set(labels)) != len(labels):
        raise ValueError(f"duplicate column in {labels}")


# One mark in a `MarkColumn` cell, as the document prints it: `Rel8`,
# `3GPP-EPS`, `OC`, and with what the document prints beside it, `All (NOTE
# 5)` (TS 29.212, whose note 5 excludes 3GPP-GPRS) or `V2X Localized User
# Plane` (TS 29.468). A file quotes a mark that is not a plain token, as it
# does an enum value name, so a mark may hold what an enum value name may.
# A lone `-` is not one: it is the dash a cell prints in place of a mark.
def _not_the_dash(value: str) -> str:
    if value == "-":
        raise ValueError("'-' is a cell's printed dash, not a mark")
    return value


Mark = Annotated[EnumValueName, pydantic.AfterValidator(_not_the_dash)]

# A row's marks per mark column its table prints, three ways: marks; `()`
# where the cell prints a dash, which TS 32.299 clause 7.1.0 gives a meaning
# ("Those Diameter AVPs that are not used are marked '-'"); and no entry
# where the cell is blank. `columns` tells a blank cell from an absent
# column.
Marks = dict[MarkColumn, tuple[Mark, ...]]


def _check_marks(name: str, marks: Marks, columns: Sequence[str]) -> None:
    declared = {mark_column(column) for column in columns}
    for column in marks:
        if column not in declared:
            raise ValueError(
                f"{name}: {column} marks set but the table has no {column} column"
            )


class AvpTableRow(Node):
    """One row of an AVP table.

    Every modelled field is optional, because AVP tables do not all have the
    same columns — TS 29.273's has no Encrypt column at all, and RFC 6733 §4.5
    has neither MAY nor SHOULD NOT nor Encrypt. Which columns a table has is
    recorded once on `AvpTable.columns` rather than per row, and the two are
    checked against each other there.

    A field is None when its column is absent *or* when the column is present
    and the cell is empty: `code` is None both ways — TS 29.329's Load row
    defers its definition to another spec — and `section` likewise (TS 29.272's
    3GPP2-MEID is defined in a 3GPP2 document, so its clause cell is blank).
    Telling the two apart is what `columns` is for.
    """

    name: AvpName
    # The row's own Vendor-ID cell, where its table prints one (oneM2M
    # TS-0004 table A.4-1): 0 for an IETF-space AVP, as the table writes it.
    vendor_id: Unsigned32 | None = None
    code: Unsigned32 | None = None
    section: SectionNumber | None = None
    data_type: DataType | None = None
    # A Type cell naming no Diameter type, as printed: TS 29.234 table 10.1.1
    # types 314 "Integer". As `RegistryRow.printed_type`, kept apart from
    # `data_type` so the statement survives without becoming a type.
    printed_type: Mark | None = None
    flag_rules: AvpFlagRules = AvpFlagRules()
    may_encrypt: bool | None = None
    # Per mark column (`MarkColumn`), what the row marks: TS 29.212's
    # `Acc-Type` and `Applicability`, TS 32.299's per-command use.
    marks: Marks = Field(default_factory=dict)

    @pydantic.model_validator(mode="after")
    def _one_type(self) -> AvpTableRow:
        if self.printed_type is not None and (
            self.data_type is not None or self.printed_type in DataType
        ):
            raise ValueError(
                f"{self.name}: printed_type {self.printed_type!r} is for a Type"
                " cell naming no Diameter type"
            )
        return self

    def stated_vendor(self, file_vendor: int) -> int | None:
        """Return the vendor space the row places the AVP in, or None.

        A Vendor-ID cell wins, even against the V flag (the linter reports
        that as `vendor-flag-mismatch`). Otherwise V under Must-not means
        IETF space and V under Must means `file_vendor`. A row with V in
        neither column states nothing.
        """
        if self.vendor_id is not None:
            return self.vendor_id
        if AvpFlag.VENDOR in self.flag_rules.must_not:
            return IETF_VENDOR
        if AvpFlag.VENDOR in self.flag_rules.must:
            return file_vendor
        return None

    def vendor_flag_conflict(self) -> str | None:
        """Describe how the row's Vendor-ID cell and V flag contradict each
        other (RFC 6733 section 4.1.1), or return None."""
        if self.vendor_id is None:
            return None
        if self.vendor_id != IETF_VENDOR and AvpFlag.VENDOR in self.flag_rules.must_not:
            return f"vendor {self.vendor_id} with V under Must-not"
        if self.vendor_id == IETF_VENDOR and AvpFlag.VENDOR in self.flag_rules.must:
            return f"vendor {IETF_VENDOR} with V under Must"
        return None


class AvpTable(Node):
    """`; Type: AVP Table` — mirrors the spec's own per-application AVP table
    (e.g. TS 29.329 table 6.3.1). `table` is the label from the `; Table:`
    directive, as printed in the spec ("6.3.1", "6.3/2").

    `columns` records the source table's columns in the source table's order,
    and is the file's own statement of its shape: an absent Encrypt column and
    an Encrypt column reading "No" are different claims, and before this
    existed they were the same `False`.
    """

    type: Literal["AVP Table"] = "AVP Table"
    # None when the source prints no label at all: RFC 6733 §4.5 introduces
    # its table with prose, not a "Table N" caption, so there is nothing for
    # `; Table:` to record.
    table: TableLabel | None = None
    source: SourceRef
    columns: Annotated[tuple[AvpTableColumn, ...], Field(min_length=1)]
    # A table section with no rows carries no information, and would mean the
    # extractor found a caption but lost its contents.
    rows: Annotated[tuple[AvpTableRow, ...], Field(min_length=1)]

    @pydantic.model_validator(mode="after")
    def _rows_match_columns(self) -> AvpTable:
        _check_columns(self.columns)
        if AvpColumn.NAME not in self.columns:
            raise ValueError("AVP table has no Name column")

        # A value under a column the table does not have is unattributable: it
        # cannot be written out, so it cannot survive a round-trip.
        absent = {
            AvpColumn.VENDOR: "vendor_id",
            AvpColumn.CODE: "code",
            AvpColumn.SECTION: "section",
            AvpColumn.TYPE: "data_type",
            AvpColumn.ENCRYPT: "may_encrypt",
        }
        if AvpColumn.TYPE not in self.columns and any(
            row.printed_type is not None for row in self.rows
        ):
            raise ValueError("printed_type set but the table has no Type column")
        flags = {
            AvpColumn.MUST: "must",
            AvpColumn.MAY: "may",
            AvpColumn.SHOULD_NOT: "should_not",
            AvpColumn.MUST_NOT: "must_not",
        }
        for row in self.rows:
            for column, field in absent.items():
                if column not in self.columns and getattr(row, field) is not None:
                    raise ValueError(
                        f"{row.name}: {field} set but the table has no"
                        f" {column.value} column"
                    )
            for column, field in flags.items():
                if column not in self.columns and getattr(row.flag_rules, field):
                    raise ValueError(
                        f"{row.name}: {field} flags set but the table has no"
                        f" {column.value} column"
                    )
            _check_marks(row.name, row.marks, self.columns)
        return self


