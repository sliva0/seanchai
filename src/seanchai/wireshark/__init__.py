"""`seanchai wireshark-plugin`: the Wireshark plugin that validates Diameter
traffic against the corpus.

`generate` writes one Lua file for Wireshark's plugin directory: the rules,
read from the corpus as `seanchai dictionary` reads it, `core.lua` (the checks,
plain Lua that runs outside Wireshark too) and `plugin.lua` (the Wireshark
side). docs/wireshark-plugin.md says what it checks.

Two lines of the file are a stable contract, for a tool that reads or edits it
without parsing Lua (`EXPLORER_LINE`, `VERSIONS_LINE`):

    -- seanchai:versions seanchai 0.2.0, corpus 2026.11.11
    local EXPLORER = "https://sliva0.github.io/seanchai-explorer/" -- seanchai:explorer

The second is the `seanchai.explorer_url` preference's default, and the one
line such a tool may rewrite.
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

from .. import corpus, dictionary, model
from ..errors import SeanchaiError
from ._rules import Places, lua_string, rules_chunk, versions

__all__ = [
    "EXPLORER",
    "EXPLORER_LINE",
    "VERSIONS_LINE",
    "Plugin",
    "PluginError",
    "generate",
]

# The explorer site, which shows each document's corrected text at a clause.
EXPLORER = "https://sliva0.github.io/seanchai-explorer/"

# The plugin's one line holding the explorer address, a plain double-quoted
# Lua string, and its one line naming the versions. Group 1 is the value.
EXPLORER_LINE = re.compile(r'^local EXPLORER = "([^"\\]*)" -- seanchai:explorer$', re.M)
VERSIONS_LINE = re.compile(r"^-- seanchai:versions (.*)$", re.M)

_HERE = Path(__file__).resolve().parent


class PluginError(SeanchaiError, ValueError):
    """Options the plugin cannot be generated with."""


@dataclass(frozen=True)
class Plugin:
    """A generated plugin, or with `rules_only` its rules alone."""

    text: str
    versions: str  # "seanchai 0.2.0, corpus 2026.11.11"
    applications: int
    avps: int

    def write(self, path: Path) -> None:
        """Write `text` to `path`, creating its directory."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.text, "utf-8")


def generate(
    books: corpus.Corpus | None = None,
    *,
    documents: Iterable[str] = (),
    application_ids: Iterable[int] = (),
    explorer: str = EXPLORER,
    rules_only: bool = False,
) -> Plugin:
    """The plugin for `books`, the installed corpus by default.

    `documents` and `application_ids` keep only those documents' or
    application ids' commands, as `seanchai dictionary` does. `explorer` is the
    explorer site each reference links to, the plugin's default for its
    `seanchai.explorer_url` preference; empty for no such links. It may not
    hold a double quote, a backslash or a control character, since the
    plugin's `EXPLORER_LINE` holds it unescaped. `rules_only` gives the rules
    alone, a Lua chunk returning the table `core.lua`'s `validate` reads, with
    `explorer` in it.

    Raises `PluginError` for such an address, and `model.ModelError` for a
    selection the corpus does not hold.
    """
    if any(char in '"\\' or ord(char) < 32 or ord(char) == 127 for char in explorer):
        raise PluginError(
            f"the explorer address {explorer!r} holds a double quote, a backslash"
            " or a control character"
        )
    if books is None:
        books = corpus.Corpus.installed()
    resolved = model.Model.build(books)
    built = dictionary.build(
        resolved,
        corpus_version=books.version,
        documents=list(documents),
        application_ids=list(application_ids),
    )
    said = versions(built)
    places = Places(books)
    if rules_only:
        text = rules_chunk(built, resolved, places, explorer)
    else:
        text = _plugin(rules_chunk(built, resolved, places), said, built, explorer)
    return Plugin(text, said, len(built.applications), len(built.avps))


def _plugin(rules: str, said: str, built: dictionary.Dictionary, explorer: str) -> str:
    """One file for Wireshark's plugin directory: the marked lines, then the
    rules, the core and the glue, each in its own function scope."""
    core = (_HERE / "core.lua").read_text("utf-8")
    glue = (_HERE / "plugin.lua").read_text("utf-8")
    return (
        "-- Seanchaí Diameter validation, generated by `seanchai wireshark-plugin`.\n"
        "-- Do not edit it. A tool may rewrite the line marked seanchai:explorer,\n"
        "-- the default of the seanchai.explorer_url preference.\n"
        f"-- seanchai:versions {said}\n"
        f"-- {len(built.applications)} applications, {len(built.avps)} AVPs\n"
        f"local EXPLORER = {lua_string(explorer)} -- seanchai:explorer\n\n"
        "local RULES = (function()\n"
        f"{rules}"
        "end)()\n\n"
        "local core = (function()\n"
        f"{core}"
        "end)()\n\n"
        f"{glue}"
    )
