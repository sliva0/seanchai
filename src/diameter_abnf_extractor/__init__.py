from __future__ import annotations

from pathlib import Path
from typing import Iterable, TextIO

import click

from .abnf_extractors.tgpp_pgf import AbnfDefinition, extract_abnf_blocks


@click.group()
def main() -> None:
    """CLI for extracting ABNF definitions from Diameter specifications."""


@main.group()
def extract() -> None:
    """Extraction commands for different specification sources."""


def write_abnf_output(
    blocks: Iterable[AbnfDefinition], buffer: TextIO, source_name: str
) -> None:
    """Write extracted ABNF definitions into the provided text buffer."""
    buffer.write(f"; Source: {source_name}\n")
    buffer.write("; Generated by diameter-abnf-extractor\n\n")

    for block in blocks:
        buffer.write(f"; {block.description}\n")
        buffer.write(block.definition)
        buffer.write("\n\n")


@extract.command("3gpp-pdf")
@click.argument("pdf_path", type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.argument("output_path", type=click.Path(dir_okay=False, path_type=Path))
def extract_3gpp_pdf(pdf_path: Path, output_path: Path) -> None:
    """Extract ABNF definitions from a 3GPP PDF into OUTPUT_PATH."""
    blocks = extract_abnf_blocks(pdf_path)
    with output_path.open("w", encoding="utf-8") as output_buffer:
        write_abnf_output(blocks, output_buffer, pdf_path.name)
    click.echo(f"Extracted {len(blocks)} ABNF block(s) to {output_path}")


@extract.command("rfc")
@click.argument("rfc_input")
@click.argument("output_path", type=click.Path(dir_okay=False, path_type=Path))
def extract_rfc(rfc_input: str, output_path: Path) -> None:
    """Placeholder for RFC ABNF extraction."""
    raise click.ClickException(
        f"RFC extraction is not implemented yet (input={rfc_input}, output={output_path})."
    )


if __name__ == "__main__":
    main()
