@dataclass
class Item:
    """One argument or element as source text, with a trailing comment that
    forces its enclosing call or tuple onto several lines."""

    text: str
    comment: str | None = None


def render_call(callee: str, items: list[Item], indent: int, prefix: str = "") -> str:
    """`prefix + callee(items)` on one line when it fits and carries no
    comment, else one item per line with a trailing comma, as ruff format
    would write it."""
    pad = " " * indent
    if all(item.comment is None and "\n" not in item.text for item in items):
        line = f"{pad}{prefix}{callee}({', '.join(item.text for item in items)})"
        if len(line) <= LINE_LENGTH:
            return line
    lines = [f"{pad}{prefix}{callee}("]
    for item in items:
        text = item.text
        comment = f"  # {item.comment}" if item.comment else ""
        lines.append(f"{pad}    {text},{comment}")
    lines.append(f"{pad})")
    return "\n".join(lines)


def render_tuple(items: list[Item], indent: int) -> str:
    """A tuple literal, multi-line under the same rule as `render_call`.
    `indent` is the column the opening parenthesis's line starts at."""
    if not items:
        return "()"
    if all(item.comment is None and "\n" not in item.text for item in items):
        single = (
            f"({items[0].text},)"
            if len(items) == 1
            else f"({', '.join(item.text for item in items)})"
        )
        if indent + len(single) <= LINE_LENGTH - 8:
            return single
    pad = " " * (indent + 4)
    lines = ["("]
    for item in items:
        comment = f"  # {item.comment}" if item.comment else ""
        lines.append(f"{pad}{item.text},{comment}")
    lines.append(" " * indent + ")")
    return "\n".join(lines)


def quoted(text: str) -> str:
    """A double-quoted literal, the library's quoting."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def import_line(module: str, names: set[str]) -> str:
    """An import sorted the way ruff's isort sorts one: constants, then
    classes, then the rest."""

    def kind(name: str) -> tuple[int, str]:
        rank = 0 if name.isupper() else 1 if name[0].isupper() else 2
        return (rank, name)

    ordered = sorted(names, key=kind)
    line = f"from {module} import {', '.join(ordered)}"
    if len(line) <= LINE_LENGTH:
        return line
    listed = "".join(f"    {name},\n" for name in ordered)
    return f"from {module} import (\n{listed})"


def attributes(
    members: list[tuple[model.Member, Definition | None]],
) -> list[str | None]:
    """Each member's attribute: None for one with no identity to decode by,
    the AVP's own spelling otherwise, with a trailing underscore where that
    is reserved and a counter where two members would share it."""
    names: list[str | None] = []
    for _, target in members:
        if target is None or target.identity is None:
            names.append(None)
            continue
        name = attribute_name(target.name)
        names.append(name + "_" if name in RESERVED_ATTRIBUTES else name)
    counts: dict[str, int] = {}
    for name in names:
        if name is not None:
            counts[name] = counts.get(name, 0) + 1
    seen: dict[str, int] = {}
    unique: list[str | None] = []
    for name in names:
        if name is None or counts[name] == 1:
            unique.append(name)
            continue
        seen[name] = seen.get(name, 0) + 1
        unique.append(name if seen[name] == 1 else f"{name}_{seen[name]}")
    return unique


def rule_items(
    members: list[tuple[model.Member, Definition | None]], qualifier: str
) -> list[Item]:
    """One `Rule` per body line, in the document's order. A rule names its
    AVP and adds only what differs from an optional, at-most-once member:
    the presence, `min` where RFC 6733's default for the presence does not
    give it, `max` where it is not one, and `attr` where the attribute is
    not the AVP's own spelling."""
    items = []
    for (member, target), attr in zip(members, attributes(members), strict=True):
        args = ["ANY_AVP" if target is None else qualifier + target.identifier]
        presence = member.rule.presence
        if presence is not ast.Presence.OPTIONAL:
            args.append(PRESENCE[presence])
        default_min = 0 if presence is ast.Presence.OPTIONAL else 1
        if member.min_occurs != default_min:
            args.append(f"min={member.min_occurs}")
        if member.max_occurs != 1:
            args.append(f"max={member.max_occurs}")
        if (
            attr is not None
            and target is not None
            and attr != attribute_name(target.name)
        ):
            args.append(f"attr={quoted(attr)}")
        hole = None if target is None else target.hole
        items.append(
            Item(f"Rule({', '.join(args)})", None if hole is None else f"hole: {hole}")
        )
    return items


def render_definition(definition: Definition) -> str:
    prefix = f"{definition.identifier} = "
    identity = definition.identity
    if identity is None:
        hole = definition.hole or ""
        return render_call(
            "AvpHole", [Item(quoted(definition.name)), Item(quoted(hole))], 0, prefix
        )
    vendor_id, code = identity
    flags = _flags(definition.sample.flag_rules)
    if flags is None:
        flags_text = "None"
    else:
        columns = zip(("must", "may", "should_not", "must_not"), flags, strict=True)
        flags_text = (
            f"FlagRules({', '.join(f'{c}={quoted(v)}' for c, v in columns if v)})"
        )
    # Name, identity, type and flags share a line even when the call does
    # not fit on one, as the library's dictionary holds one AVP per line.
    head = [quoted(definition.name), str(code), str(vendor_id)]
    head += [definition.avp_class or "None", flags_text]
    items = [Item(", ".join(head))]
    if definition.members:
        rules = render_tuple(rule_items(definition.members, ""), 4)
        items.append(Item(f"members={rules}"))
    sample = definition.sample
    if isinstance(sample, model.Enumerated):
        values = [
            Item(f"({quoted(value.name)}, {value.value})")
            for value in sample.values
            if isinstance(value, ast.EnumValue)
        ]
        reserved = [
            Item(f"({value.first}, {value.last})")
            for value in sample.values
            if isinstance(value, ast.ReservedValues)
        ]
        if values:
            items.append(Item(f"values={render_tuple(values, 4)}"))
        if reserved:
            items.append(Item(f"reserved={render_tuple(reserved, 4)}"))
    documents = [Item(quoted(document)) for document in sorted(definition.documents)]
    items.append(Item(f"defined_in={render_tuple(documents, 4)}"))
    if definition.wireshark_alias is not None:
        items.append(Item(f"wireshark_name={quoted(definition.wireshark_alias)}"))
    if definition.hole is not None:
        items.append(Item(f"hole={quoted(definition.hole)}"))
    rendered = render_call("AvpDef", items, 0, prefix)
    if isinstance(sample, model.Enumerated) and sample.values_source is not None:
        # The clause names where the values are defined, in its words: with
        # no values beside it (TS 29.272's Trace-Depth) the comment is all a
        # reader gets of the list.
        cited = f"{sample.defined_in} clause {sample.section}"
        comment = f"Values: {sample.values_source} ({cited})."
        lines = textwrap.wrap(comment, 86, break_on_hyphens=False)
        rendered = "".join(f"# {line}\n" for line in lines) + rendered
    return rendered


def _sort_key(definition: Definition) -> tuple:
    return (definition.identity or (2**32, 0), definition.identifier)


def ordered(definitions: Definitions) -> list[Definition]:
    """By identity, except that a grouped AVP's members come before it, so
    every reference in `avps.py` is to a name already bound."""
    done: set[int] = set()
    order: list[Definition] = []

    def visit(definition: Definition) -> None:
        if id(definition) in done:
            return
        done.add(id(definition))
        targets = [target for _, target in definition.members if target is not None]
        for target in sorted(targets, key=_sort_key):
            visit(target)
        order.append(definition)

    for definition in sorted(definitions, key=_sort_key):
        visit(definition)
    return order


def render_avps(definitions: Definitions, sources: list[str]) -> str:
    order = ordered(definitions)
    complete = [d for d in order if d.identity is not None]
    holes = [d for d in order if d.identity is None]
    classes = sorted({d.avp_class for d in complete if d.avp_class})
    support = {"AvpDef", "AvpHole"}
    if any(d.sample.flag_rules is not None for d in complete):
        support.add("FlagRules")
    for definition in complete:
        for member, target in definition.members:
            support.add("Rule")
            if target is None:
                support.add("ANY_AVP")
            if member.rule.presence is not ast.Presence.OPTIONAL:
                support.add(PRESENCE[member.rule.presence])
    lines = [
        MARKER,
        '"""AVP definitions shared by the generated protocol-specific commands.',
        "",
        "One `AvpDef` per distinct reading, listed in `BY_IDENTITY` under its",
        "`(vendor-id, code)`: an AVP two documents define differently has one",
        "per reading, and each command's rules name its own document's.",
        "`BY_WIRESHARK_NAME` finds a definition by Wireshark's spelling where it",
        "differs from the document's. `HOLES` are member names the corpus",
        "resolves to no identity.",
        "",
        "Generated from:",
        "",
        *(f"- {source}" for source in sources),
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    if classes:
        lines.append("from diameter.message.avp import (")
        lines += [f"    {name}," for name in classes]
        lines += [")", ""]
    lines.append(import_line("._base", support))
    lines += ["", ""]
    for definition in holes:
        lines.append(render_definition(definition))
    if holes:
        lines.append("")
    for definition in complete:
        lines.append(render_definition(definition))
    lines += ["", ""]
    by_identity: dict[tuple[int, int], list[str]] = {}
    for definition in sorted(complete, key=_sort_key):
        identity = definition.identity
        assert identity is not None
        by_identity.setdefault(identity, []).append(definition.identifier)
    lines.append("BY_IDENTITY: dict[tuple[int, int], tuple[AvpDef, ...]] = {")
    for (vendor_id, code), identifiers in sorted(by_identity.items()):
        readings = render_tuple([Item(name) for name in identifiers], 4)
        lines.append(f"    ({vendor_id}, {code}): {readings},")
    lines.append("}")
    aliases: dict[str, list[str]] = {}
    for definition in sorted(complete, key=_sort_key):
        if definition.wireshark_alias is not None:
            aliases.setdefault(definition.wireshark_alias, []).append(
                definition.identifier
            )
    lines.append("BY_WIRESHARK_NAME: dict[str, tuple[AvpDef, ...]] = {")
    for alias, identifiers in sorted(aliases.items()):
        readings = render_tuple([Item(name) for name in identifiers], 4)
        lines.append(f"    {quoted(alias)}: {readings},")
    lines.append("}")
    hole_items = [Item(d.identifier) for d in holes]
    lines.append(f"HOLES: tuple[AvpHole, ...] = {render_tuple(hole_items, 0)}")
    return "\n".join(lines) + "\n"


def render_unit(unit: Unit) -> str:
    application = unit.application
    if application.application_id is None:
        application_text = "None"
        heading = (
            f"{unit.name} commands, clause {application.clause}. The document's"
            " command headers print no application id."
        )
    else:
        application_text = str(application.application_id)
        heading = (
            f"{unit.name} commands, clause {application.clause}, application"
            f" {application.application_id}."
        )
    class_lines: list[str] = []
    imports = {"ProtocolMessage"}
    uses_datetime = False
    uses_any = False
    names = []
    for code, (base, base_spelled) in unit.bases.items():
        names.append(base)
        class_lines += [
            "",
            "",
            f"class {base}(ProtocolMessage):",
            f'    """The {base_spelled} command, code {code}."""',
            "",
            f"    code: int = {code}",
            f"    name: str = {quoted(base_spelled)}",
            "    application_id = APPLICATION_ID",
        ]
        for command in unit.commands:
            if command.message.command_code != code:
                continue
            message = command.message
            names.append(command.class_name)
            clauses = ", ".join(command.sections)
            plural = "s" if len(command.sections) > 1 else ""
            body = [
                "",
                "",
                f"class {command.class_name}({base}):",
                f'    """{message.name}, clause{plural} {clauses}."""',
                "",
            ]
            annotations = []
            for (_, target), attr in zip(
                command.members, attributes(command.members), strict=True
            ):
                if attr is None or target is None:
                    continue
                python_type = target.python_type
                uses_datetime |= python_type.startswith("datetime")
                uses_any |= python_type == "Any"
                if python_type == "Grouped":
                    imports.add("Grouped")
                annotations.append((attr, python_type, target))
            for attr, python_type, target in annotations:
                repeated = any(
                    t is target and m.max_occurs != 1 for m, t in command.members
                )
                spelled = f"list[{python_type}]" if repeated else python_type
                body.append(f"    {attr}: {spelled}")
            if annotations:
                body.append("")
            request = ast.CommandFlag.REQUEST in message.flags
            if request != message.name.lower().endswith("-request"):
                body.append(
                    "    # As printed: the header's REQ flag disagrees with the"
                    " command's name."
                )
            body.append(f"    is_request = {request}")
            body.append(
                f"    is_proxyable = {ast.CommandFlag.PROXIABLE in message.flags}"
            )
            if ast.CommandFlag.ERROR in message.flags:
                body.append("    is_error = True")
            items = rule_items(command.members, "avps.")
            for member, target in command.members:
                if target is None:
                    imports.add("ANY_AVP")
                if member.rule.presence is not ast.Presence.OPTIONAL:
                    imports.add(PRESENCE[member.rule.presence])
            if items:
                imports.add("Rule")
            body.append(f"    avp_rules = {render_tuple(items, 4)}")
            class_lines += body
    lines = [MARKER, f'"""{heading}', "", f"Generated from {unit.title}.", '"""', ""]
    lines.append("from __future__ import annotations")
    lines.append("")
    if uses_datetime:
        lines += ["import datetime", ""]
    if uses_any:
        lines += ["from typing import Any", ""]
    lines.append("from . import avps")
    lines.append(import_line("._base", imports))
    lines.append("")
    lines.append(f"__all__ = {render_tuple([Item(quoted(n)) for n in names], 0)}")
    lines.append("")
    lines.append(f"APPLICATION_ID: int | None = {application_text}")
    lines += class_lines
    lines += ["", ""]
    commands = [Item(f"{code}: {base}") for code, (base, _) in unit.bases.items()]
    lines.append("COMMANDS: dict[int, type[ProtocolMessage]] = {")
    lines += [f"    {item.text}," for item in commands]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_init(units: list[Unit], sources: list[str]) -> str:
    lines = [
        MARKER,
        '"""Protocol-specific Diameter commands, one module per application and',
        "interface, over the AVP definitions in `avps`.",
        "",
        "Generated from:",
        "",
        *(f"- {source}" for source in sources),
        "",
        "Modules:",
        "",
    ]
    for unit in units:
        application = unit.application
        what = (
            "no application id"
            if application.application_id is None
            else f"application {application.application_id}"
        )
        lines.append(
            f"- `{unit.module}`: {unit.name} clause {application.clause}, {what}"
        )
    lines.append('"""')
    lines.append("")
    modules = ["avps", *(unit.module for unit in units)]
    lines.append(f"__all__ = {render_tuple([Item(quoted(m)) for m in modules], 0)}")
    return "\n".join(lines) + "\n"


