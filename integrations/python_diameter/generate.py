def generate(
    built: model.Model, books: corpus.Corpus, references: list[str]
) -> dict[str, str]:
    """Every file of the package for `references`, by file name."""
    titles: dict[str, str] = {}
    for entry in books:
        if entry.reference not in titles:
            version = entry.spec.version
            titles[entry.reference] = entry.spec.specification + (
                f" V{version}" if version else ""
            )
    definitions = Definitions()
    units: list[Unit] = []
    for reference in references:
        applications = built.applications(reference)
        for application, module in zip(
            applications, module_names(applications), strict=True
        ):
            units.append(
                collect_unit(application, module, titles[reference], definitions)
            )
        for avp in built.avps(reference):
            definitions.add(avp)
        for hole in built.holes(reference):
            definitions.add(hole)
    definitions.name()
    documents = {document for d in definitions for document in d.documents}
    documents |= set(references)
    sources = sorted(titles[document] for document in documents if document in titles)
    files = {
        "__init__.py": render_init(units, sources),
        "_base.py": MARKER + "\n" + (_HERE / "_base.py").read_text(encoding="utf-8"),
        "avps.py": render_avps(definitions, sources),
    }
    for unit in units:
        files[f"{unit.module}.py"] = render_unit(unit)
    return files


def write(output: Path, files: dict[str, str]) -> None:
    """Replace the package at `output`, refusing a directory holding
    anything this script did not write."""
    if output.exists():
        for path in output.iterdir():
            if path.name == "__pycache__":
                continue
            generated = (
                path.is_file()
                and path.suffix == ".py"
                and path.read_text(encoding="utf-8").startswith(MARKER)
            )
            if not generated:
                raise SystemExit(
                    f"error: {output} holds {path.name}, which generate.py did"
                    " not write; choose an empty or generated directory"
                )
        shutil.rmtree(output)
    output.mkdir(parents=True)
    for name, text in sorted(files.items()):
        (output / name).write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate protocol-specific python-diameter command classes."
    )
    parser.add_argument(
        "specifications", nargs="*", help="references, e.g. TS29.229 or 29.229"
    )
    parser.add_argument(
        "--all", action="store_true", help="every specification the corpus holds"
    )
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument(
        "--corpus",
        type=Path,
        default=_HERE.parents[1] / "dad",
        help="the corpus directory (default: the repository's dad/)",
    )
    parser.add_argument(
        "--dictionary",
        type=Path,
        help="a Wireshark dictionary directory, for Wireshark's AVP names",
    )
    args = parser.parse_args(argv)
    if bool(args.specifications) == args.all:
        parser.error("name specifications or pass --all, not both")
    books = corpus.Corpus.load([args.corpus])
    built = model.Model.build(books, dictionary=args.dictionary)
    if args.all:
        references = built.references()
    else:
        references = list(dict.fromkeys(map(reference_of, args.specifications)))
        missing = [r for r in references if r not in built.references()]
        if missing:
            print(f"error: the corpus holds no {', '.join(missing)}", file=sys.stderr)
            return 2
    write(args.output, generate(built, books, references))
    return 0


if __name__ == "__main__":
    sys.exit(main())
