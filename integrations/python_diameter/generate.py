@dataclass
class Generated:
    files: dict[str, str]
    # Per specification, the additions its modules and dictionary view need.
    additions: dict[str, set[str]]


def generate(
    built: model.Model, books: corpus.Corpus, references: list[str], library: Library
) -> Generated:
    """Every file of the package for `references`, by file name."""
    titles: dict[str, str] = {}
    for entry in books:
        if entry.reference not in titles:
            version = entry.spec.version
            titles[entry.reference] = entry.spec.specification + (
                f" V{version}" if version else ""
            )
    definitions = Definitions()
    units: list[Unit] = []
    # Per specification, its dictionary view: an AVP the document defines or
    # re-uses belongs in the additions even where no command names it.
    views: dict[str, list[Definition]] = {}
    for reference in references:
        applications = built.applications(reference)
        for application, module in zip(
            applications, module_names(applications), strict=True
        ):
            units.append(
                collect_unit(
                    built, application, module, titles[reference], definitions, library
                )
            )
        view = [definitions.add(avp) for avp in built.avps(reference)]
        view += [definitions.add(hole) for hole in built.holes(reference)]
        views[reference] = view
    resolver = Resolver(library, definitions)
    documents = {document for d in definitions for document in d.documents}
    documents |= set(references)
    sources = sorted(titles[document] for document in documents if document in titles)
    files = {}
    per_module: dict[str, set[str]] = {}
    for unit in units:
        files[f"{unit.module}.py"] = render_unit(unit, resolver)
        needed: set[str] = set()
        seen: set[int] = set()
        for command in unit.commands:
            for _, target in command.members:
                resolver.needs(target, needed, seen)
        per_module[unit.module] = needed
    per_spec: dict[str, set[str]] = {}
    for reference in references:
        needed = set()
        seen = set()
        for definition in views[reference]:
            resolver.needs(definition, needed, seen)
        for unit in units:
            if unit.reference == reference:
                needed |= per_module[unit.module]
        per_spec[reference] = needed
    counts = {module: len(needed) for module, needed in per_module.items()}
    files["__init__.py"] = render_init(units, sources, counts, library.version)
    files["additions.py"] = render_additions(resolver, sources)
    return Generated(files, per_spec)


def write(output: Path, files: dict[str, str]) -> None:
    """Replace the package at `output`, refusing a directory holding
    anything this script did not write."""
    if output.exists():
        for path in output.iterdir():
            if path.name == "__pycache__":
                continue
            generated = (
                path.is_file()
                and path.suffix == ".py"
                and path.read_text(encoding="utf-8").startswith(MARKER)
            )
            if not generated:
                raise SystemExit(
                    f"error: {output} holds {path.name}, which generate.py did"
                    " not write; choose an empty or generated directory"
                )
        shutil.rmtree(output)
    output.mkdir(parents=True)
    for name, text in sorted(files.items()):
        (output / name).write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate python-diameter command modules per application."
    )
    parser.add_argument(
        "specifications", nargs="*", help="references, e.g. TS29.229 or 29.229"
    )
    parser.add_argument(
        "--all", action="store_true", help="every specification the corpus holds"
    )
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument(
        "--corpus",
        type=Path,
        default=_HERE.parents[1] / "dad",
        help="the corpus directory (default: the repository's dad/)",
    )
    parser.add_argument(
        "--dictionary",
        type=Path,
        help="a Wireshark dictionary directory, for Wireshark's AVP names",
    )
    args = parser.parse_args(argv)
    if bool(args.specifications) == args.all:
        parser.error("name specifications or pass --all, not both")
    books = corpus.Corpus.load([args.corpus])
    built = model.Model.build(books, dictionary=args.dictionary)
    if args.all:
        references = built.references()
    else:
        references = list(dict.fromkeys(map(reference_of, args.specifications)))
        missing = [r for r in references if r not in built.references()]
        if missing:
            print(f"error: the corpus holds no {', '.join(missing)}", file=sys.stderr)
            return 2
    generated = generate(built, books, references, Library.load())
    write(args.output, generated.files)
    for reference in references:
        needed = len(generated.additions[reference])
        print(f"{reference}: {needed} addition{'' if needed == 1 else 's'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
