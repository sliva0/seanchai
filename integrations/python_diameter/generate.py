def _flags(flag_rules: ast.AvpFlagRules | None) -> tuple[str, str, str, str] | None:
    if flag_rules is None:
        return None
    order = list(ast.AvpFlag)

    def letters(flags: frozenset[ast.AvpFlag]) -> str:
        return "".join(flag.value for flag in sorted(flags, key=order.index))

    return (
        letters(flag_rules.must),
        letters(flag_rules.may),
        letters(flag_rules.should_not),
        letters(flag_rules.must_not),
    )


@dataclass(eq=False)
class Definition:
    """One distinct AVP reading the generated set reaches: a complete `Avp`,
    or a `Hole` with or without an identity."""

    sample: model.Avp | model.Hole
    # Each member's target; None for the `* [ AVP ]` wildcard.
    members: list[tuple[model.Member, Definition | None]]
    documents: set[str] = field(default_factory=set)

    @property
    def name(self) -> str:
        return self.sample.name

    @property
    def identity(self) -> Identity | None:
        sample = self.sample
        if sample.vendor_id is None or sample.code is None:
            return None
        return (sample.vendor_id, sample.code)

    @property
    def is_grouped(self) -> bool:
        return self.sample.data_type is ast.DataType.GROUPED

    @property
    def hole(self) -> str | None:
        return str(self.sample) if isinstance(self.sample, model.Hole) else None

    @property
    def wireshark_alias(self) -> str | None:
        """Wireshark's name where it is not the document's spelling."""
        wireshark_name = self.sample.wireshark_name
        return None if wireshark_name == self.name else wireshark_name

    @property
    def is_mandatory(self) -> bool | None:
        """The M bit the flag rules fix, or None where they leave it open."""
        # An IETF AVP whose documents state no M rule has it application-
        # defined (`model.FlagRules`, RFC 6733 section 4.1): in no column,
        # so None, and the library encodes the dictionary's default, as for
        # an M under May.
        flag_rules = self.sample.flag_rules
        if flag_rules is None:
            return None
        if ast.AvpFlag.MANDATORY in flag_rules.must:
            return True
        if ast.AvpFlag.MANDATORY in flag_rules.must_not:
            return False
        return None


def _body_signature(members: list[tuple[model.Member, Definition | None]]) -> tuple:
    return tuple(
        (
            member.rule.presence,
            member.min_occurs,
            member.max_occurs,
            None if target is None else id(target),
        )
        for member, target in members
    )


class Definitions:
    """Every distinct reading, deduplicated on what goes on the wire.

    Every reading of one identity references the same `AVP_*` constant; the
    readings stay apart because a grouped AVP's members decide which grouped
    class its rules name (TS 29.273's `SIP-Auth-Data-Item` body differs
    from TS 29.229's), and a reading whose type the library's entry does not
    carry is what `additions.py` corrects.
    """

    def __init__(self) -> None:
        self._by_signature: dict[tuple, Definition] = {}
        # Readings already seen, by object identity: an `Avp` hashes its
        # whole member tree, and the same objects come back for every body
        # naming them. `_seen` keeps them alive so no id is reused.
        self._memo: dict[int, Definition] = {}
        self._seen: list[object] = []

    def __iter__(self):
        return iter(self._by_signature.values())

    def add(self, found: model.Avp | model.Hole) -> Definition:
        known = self._memo.get(id(found))
        if known is not None:
            return known
        members = []
        if isinstance(found, model.Grouped):
            members = [(member, self.member(member)) for member in found.members]
        signature = self._signature(found, members)
        definition = self._by_signature.get(signature)
        if definition is None:
            definition = Definition(found, members)
            self._by_signature[signature] = definition
        definition.documents.add(
            found.defined_in if isinstance(found, model.Avp) else found.reference
        )
        self._memo[id(found)] = definition
        self._seen.append(found)
        return definition

    def member(self, member: model.Member) -> Definition | None:
        """The definition a body line points at; None for the wildcard."""
        if member.avp is not None:
            return self.add(member.avp)
        if member.hole is not None:
            return self.add(member.hole)
        if member.name == "AVP":
            return None
        # A grouped AVP among its own descendants: the model stops there
        # rather than recurse, and the name stays a hole here.
        return self.add(model.Hole("", member.name, (model.DEFINITION,)))

    @staticmethod
    def _signature(
        found: model.Avp | model.Hole,
        members: list[tuple[model.Member, Definition | None]],
    ) -> tuple:
        flags = _flags(found.flag_rules)
        if isinstance(found, model.Hole):
            return ("hole", str(found), found.vendor_id, found.code, found.data_type)
        values = tuple(
            (value.name, value.value)
            if isinstance(value, ast.EnumValue)
            else (value.first, value.last)
            for value in getattr(found, "values", ())
        )
        return (
            found.name,
            found.identity,
            found.data_type,
            flags,
            _body_signature(members),
            values,
        )


def _order(definition: Definition) -> tuple:
    """An order that does not depend on hashing: identity, first document,
    flags, hole, then the members' names."""
    return (
        definition.identity or (2**32, 0),
        definition.name,
        min(definition.documents, default=""),
        _flags(definition.sample.flag_rules) or (),
        definition.hole or "",
        [(member.rule.presence.value, member.name) for member, _ in definition.members],
    )


# The mark columns a member's comment carries from its command's interface
# clause. None of them names an interface: each interface clause has tables
# of its own, and these say which access types and features within it an
# AVP serves (TS 29.212 table 5.3.0.1 notes 3 and 9), or on which reference
# points (TS 29.061 table 9a).
_NOTED_MARKS = (
    ast.MarkColumn.ACCESS_TYPES,
    ast.MarkColumn.APPLICABILITY,
    ast.MarkColumn.REFERENCE_POINTS,
)


def member_note(
    built: model.Model,
    application: model.Application,
    message: model.Message,
    member: model.Member,
) -> str | None:
    """What the tables mark about `member` of `message`, for a comment.

    The ABNF decides membership, being what goes on the wire; the marks are
    comments. A command column (TS 32.299's ACR, ACA, CCR, CCA) is read from
    any of the document's tables, which tabulate per command rather than
    per clause: table 7.1.0.1 marks ACA's `Error-Message` "-", "not used"
    by clause 7.1.0, though clause 6.2.3's ABNF lists it. Every other mark
    column is read from the tables in the command's own interface clause:
    TS 29.212's Gxx re-used table re-marks Gx's AVPs for Gxx. The first row
    printing a column with a mark or a dash speaks for it; a blank cell
    says nothing.
    """
    if member.avp is None and member.hole is None:
        return None  # the `* [ AVP ]` wildcard
    rows = built.marks(application.reference, member.name)
    here = [
        row for row in rows if ast.interface_clause(row.section) == application.clause
    ]
    columns = [(noted, here) for noted in _NOTED_MARKS]
    if message.abbreviation in ast.MarkColumn:
        columns.insert(0, (ast.MarkColumn(message.abbreviation), list(rows)))
    spelled = []
    for column, candidates in columns:
        found = next(
            (
                (row, marks)
                for row in candidates
                if (marks := row.marks.get(column)) is not None
            ),
            None,
        )
        if found is None:
            continue
        row, marks = found
        if not marks:
            spelled.append(f"{column.value}: - (unused, table {row.table})")
        elif marks != ("All",):  # every access type restricts nothing
            spelled.append(f"{column.value}: {', '.join(marks)}")
    return "; ".join(spelled) or None


@dataclass
class Command:
    """One generated Request or Answer class."""

    message: model.Message
    members: list[tuple[model.Member, Definition | None]]
    class_name: str
    # The clauses printing this body; more than one where a document
    # repeats a command identically per procedure (TS 29.273's STa STR).
    sections: list[str]
    # Per member, what the tables mark about it, for a comment.
    notes: list[str | None]


@dataclass
class Unit:
    """One generated module: one application on one interface."""

    module: str
    reference: str
    application: model.Application
    # "3GPP TS 29.229 V18.1.0", the copy generated from.
    title: str
    # Base class name and command name per command code, in first-appearance
    # order.
    bases: dict[int, tuple[str, str]]
    commands: list[Command]
    # The registry's name for the application, where the document names it
    # nowhere: "3GPP Cx/Px", TS 29.230 table 4.1.
    registered: str | None = None

    @property
    def name(self) -> str:
        """The document's name without its version: "3GPP TS 29.229"."""
        return self.title.split(" V")[0]


def module_names(applications: tuple[model.Application, ...]) -> list[str]:
    """`ts29_229` for a document with one application; the interface clause
    appended where a document has several (`ts29_212_5a`), and the
    application id where several share one clause (`ts29_272_16777308`)."""
    clauses = {application.clause for application in applications}
    per_clause: dict[str, int] = {}
    for application in applications:
        per_clause[application.clause] = per_clause.get(application.clause, 0) + 1
    names = []
    for application in applications:
        parts = [slug(application.reference)]
        if len(clauses) > 1:
            parts.append(application.clause.lower().replace(".", "_"))
        if per_clause[application.clause] > 1:
            parts.append(str(application.application_id))
        names.append("_".join(parts))
    return names


def command_base(name: str) -> str:
    for suffix in ("-Request", "-Answer"):
        if name.lower().endswith(suffix.lower()):
            return name[: -len(suffix)]
    return name


def collect_unit(
    built: model.Model,
    application: model.Application,
    module: str,
    title: str,
    definitions: Definitions,
    library: Library,
) -> Unit:
    bases: dict[int, tuple[str, str]] = {}
    commands: list[Command] = []
    by_name: dict[str, list[Command]] = {}
    for message in application.messages:
        base = command_base(message.name)
        # The library's class name for the code where it has one, so the
        # document's `CC-Request` is `CreditControlRequest` as there.
        base_class, base_name = library.commands.get(
            message.command_code, (class_name(base), base)
        )
        bases.setdefault(message.command_code, (base_class, base_name))
        members = [(member, definitions.member(member)) for member in message.avps]
        notes = [
            member_note(built, application, message, member) for member in message.avps
        ]
        request = ast.CommandFlag.REQUEST in message.flags
        named_request = message.name.lower().endswith("-request")
        named_answer = message.name.lower().endswith("-answer")
        # By the name where it says, as the library's `to_answer` pairs the
        # two by name; by the REQ flag where the name does not.
        is_request = named_request or (request and not named_answer)
        name = bases[message.command_code][0] + ("Request" if is_request else "Answer")
        alike = by_name.setdefault(name, [])
        same = [
            command
            for command in alike
            if _body_signature(command.members) == _body_signature(members)
            and command.notes == notes
            and command.message.flags == message.flags
        ]
        if same:
            same[0].sections.append(message.section)
            continue
        if alike:
            # The same command printed twice with different bodies (TS
            # 29.273's AAR in clauses 9.2.2.2.1 and 9.2.2.5.1): the later
            # copy keeps its clause in its name.
            name = f"{name}_{message.section.replace('.', '_')}"
        command = Command(message, members, name, [message.section], notes)
        alike.append(command)
        commands.append(command)
    registered = None
    if application.application_id is not None and application.name is None:
        registered = next(
            (
                f"{allocation.entry.name}, {allocation.reference} table"
                f" {allocation.table}"
                for allocation in built.registry(
                    ast.RegistryKind.APPLICATION_IDS, application.application_id
                )
                if isinstance(allocation.entry, ast.RegistryRow)
                and allocation.entry.name is not None
            ),
            None,
        )
    return Unit(
        module, application.reference, application, title, bases, commands, registered
    )


# --- resolving against the library -------------------------------------------


@dataclass
class Addition:
    """A dictionary entry the library lacks (`replaces` None) or holds with
    a value class the document does not give (`replaces` that class)."""

    identity: Identity
    name: str
    constant: str
    avp_class: str
    mandatory: bool
    replaces: str | None
    readings: list[Definition]
    notes: list[str] = field(default_factory=list)


@dataclass
class GroupedAddition:
    """A grouped class in `grouped.py`'s shape, for a reading the library
    has no class for, or whose class lacks members the reading names."""

    definition: Definition
    class_name: str


class Resolver:
    """Which constant, value class and grouped class each reading takes:
    the library's wherever it carries what the document says, an addition
    wherever it does not."""

    def __init__(self, library: Library, definitions: Definitions) -> None:
        self.library = library
        self.definitions = sorted(definitions, key=_order)
        self.additions: dict[Identity, Addition] = {}
        # Notes on identities whose readings disagree among themselves while
        # one of them agrees with the library's entry, which stays.
        self.kept: list[str] = []
        self.grouped: dict[int, GroupedAddition] = {}
        self._gaps: dict[int, list[str]] = {}
        by_identity: dict[Identity, list[Definition]] = {}
        for definition in self.definitions:
            if definition.identity is not None:
                by_identity.setdefault(definition.identity, []).append(definition)
        taken = set(library.names)
        for identity, readings in sorted(by_identity.items()):
            addition = self._addition(identity, readings, taken)
            if addition is not None:
                self.additions[identity] = addition
                taken.add(addition.constant)
        self._name_grouped(taken)

    def _addition(
        self, identity: Identity, readings: list[Definition], taken: set[str]
    ) -> Addition | None:
        library = self.library
        typed = [d for d in readings if d.sample.data_type is not None]
        types = list(dict.fromkeys(d.sample.data_type for d in typed))
        first = typed[0] if typed else readings[0]
        notes = []
        if len(types) > 1:
            stated = ", ".join(
                f"{min(d.documents)} {d.sample.data_type.value}"
                for d in typed
                if d.sample.data_type is not None
            )
            notes.append(f"the documents disagree on its type: {stated}")
        entry = library.entries.get(identity)
        if entry is not None:
            held = entry["type"].__name__
            agree = [t for t in types if held in COMPATIBLE.get(t, {AVP_CLASS[t]})]
            if not types or agree:
                if notes:
                    self.kept.append(
                        f"{library.constants[identity]} ({first.name}): "
                        f"{notes[0]}; the library's {held} carries"
                        f" {agree[0].value}, so its entry stays"
                    )
                return None
            data_type = types[0]
            return Addition(
                identity,
                entry["name"],
                library.constants[identity],
                AVP_CLASS[data_type],
                bool(entry.get("mandatory")),
                held,
                readings,
                notes,
            )
        vendor, code = identity
        if vendor not in library.vendors:
            raise SystemExit(
                f"error: {first.name} is vendor {vendor}, for which the library"
                " has no VENDOR_ constant"
            )
        prefix = library.vendors[vendor].removeprefix("VENDOR_")
        base = "AVP_" + ("" if vendor == 0 else prefix + "_")
        constant = base + constant_case(first.name)
        if constant in taken:
            constant = f"{constant}_{code}"
        elsewhere = [
            f"code {other_code}, vendor {other_vendor}"
            for other_vendor, other_code in library.by_name.get(first.name, ())
        ]
        if elsewhere:
            listed = " and ".join(elsewhere)
            notes.append(f"the library's dictionary has {first.name} as {listed}")
        if not types:
            notes.append("no document states its type")
        mandatory = first.is_mandatory is True
        avp_class = AVP_CLASS[types[0]] if types else "Avp"
        return Addition(
            identity, first.name, constant, avp_class, mandatory, None, readings, notes
        )

    def constant(self, definition: Definition) -> str | None:
        identity = definition.identity
        if identity is None:
            return None
        addition = self.additions.get(identity)
        if addition is not None:
            return addition.constant
        return self.library.constants[identity]

    def avp_class(self, definition: Definition) -> str:
        """The value class the AVP decodes into once the additions are
        registered, corrections included."""
        identity = definition.identity
        assert identity is not None
        addition = self.additions.get(identity)
        if addition is not None:
            return addition.avp_class
        return self.library.entries[identity]["type"].__name__

    def covered(self, definition: Definition) -> bool:
        return not self.gaps(definition)

    def gaps(self, definition: Definition) -> list[str]:
        """What keeps the library's grouped class for the reading from
        carrying all of it: no class at all, a member the class does not
        hold, a member the class holds in a class that does not cover the
        reading's own member, or a member it encodes with an M bit the
        reading's flag rules forbid or require. Empty where the library's
        class serves: identities, nesting and M bits all agree.

        The M bit is the one flag an `AvpGenDef` decides; V follows the
        vendor-id the identity already compares. A member whose flag rules
        leave M open accepts either."""
        known = self._gaps.get(id(definition))
        if known is not None:
            return known
        holder = (
            None
            if definition.identity is None
            else self.library.grouped.get(definition.identity)
        )
        if holder is None:
            gaps = ["the library has no class for it"]
        else:
            members = self.library.members(holder)
            lacking = []
            replaced = []
            flagged: dict[bool, list[str]] = {True: [], False: []}
            for _, target in definition.members:
                if target is None or target.identity is None:
                    continue
                if target.identity not in members:
                    lacking.append(target.name)
                    continue
                type_class, mandatory = members[target.identity]
                if target.is_grouped and (
                    not self.covered(target)
                    or type_class is not self.library.grouped[target.identity]
                ):
                    replaced.append(target.name)
                if target.is_mandatory is not None and target.is_mandatory != mandatory:
                    flagged[mandatory].append(target.name)
            gaps = []
            if lacking:
                gaps.append(f"`{holder.__name__}` lacks {', '.join(lacking)}")
            if replaced:
                gaps.append(
                    f"`{holder.__name__}` holds {', '.join(replaced)} in a class"
                    " this reading's does not match"
                )
            for mandatory, names in flagged.items():
                if names:
                    gaps.append(
                        f"`{holder.__name__}` encodes {', '.join(names)} with M"
                        f" {'set' if mandatory else 'clear'}, which this reading's"
                        f" flag rules {'forbid' if mandatory else 'require'}"
                    )
        self._gaps[id(definition)] = gaps
        return gaps

    def _name_grouped(self, taken: set[str]) -> None:
        """Name a grouped class for every grouped reading the library's does
        not cover: the AVP's name in the library's spelling, with the
        reading's first document as a suffix where the library already binds
        the name or an earlier reading took it (`SipAuthDataItem_TS29_273`),
        so an addition never shadows a name the star imports bring in."""
        sharing: dict[str, list[Definition]] = {}
        for definition in self.definitions:
            if not definition.is_grouped or definition.identity is None:
                continue
            if self.covered(definition):
                continue
            holder = self.library.grouped.get(definition.identity)
            base = holder.__name__ if holder else class_name(definition.name)
            sharing.setdefault(base, []).append(definition)
        for base, readings in sharing.items():
            replaces = base if base in self.library.names else None
            for index, definition in enumerate(readings):
                name = base
                if index or replaces:
                    name = f"{base}_{slug(min(definition.documents)).upper()}"
                unique, number = name, 1
                while unique in taken:
                    number += 1
                    unique = f"{name}_{number}"
                taken.add(unique)
                self.grouped[id(definition)] = GroupedAddition(definition, unique)

    def type_class(self, definition: Definition) -> str | None:
        """The grouped class a grouped reading's rules name."""
        if not definition.is_grouped:
            return None
        added = self.grouped.get(id(definition))
        if added is not None:
            return added.class_name
        assert definition.identity is not None
        return self.library.grouped[definition.identity].__name__

    def imports(self, definition: Definition | None) -> list[str]:
        """The names from `additions.py` a rule naming the reading spells:
        a new constant and a grouped class. A corrected entry keeps the
        library's constant."""
        if definition is None or definition.identity is None:
            return []
        names = []
        addition = self.additions.get(definition.identity)
        if addition is not None and addition.replaces is None:
            names.append(addition.constant)
        added = self.grouped.get(id(definition))
        if added is not None:
            names.append(added.class_name)
        return names

    def needs(
        self, definition: Definition | None, found: set[str], seen: set[int]
    ) -> None:
        """Every addition a reading reaches, members included, by the name
        it is bound to: encoding a member needs its dictionary entry
        whichever grouped class holds it."""
        if definition is None or definition.identity is None:
            return
        if id(definition) in seen:
            return
        seen.add(id(definition))
        addition = self.additions.get(definition.identity)
        if addition is not None:
            found.add(addition.constant)
        added = self.grouped.get(id(definition))
        if added is not None:
            found.add(added.class_name)
        for _, target in definition.members:
            self.needs(target, found, seen)


# --- rendering ---------------------------------------------------------------


@dataclass
class Entry:
    """One `AvpGenDef` line, or a comment standing for a member it cannot
    be written for."""

    attr: str | None
    text: str
    python_type: str | None = None
    repeated: bool = False


def gen_defs(
    members: list[tuple[model.Member, Definition | None]],
    resolver: Resolver,
    notes: list[str | None] | None = None,
) -> list[Entry]:
    """One `AvpGenDef` per member, in the document's order, as the library
    writes them: attribute, constant, vendor, then `is_required` from the
    brackets, `is_mandatory` from the flag rules where they fix the M bit,
    and the grouped class. What `AvpGenDef` has no slot for is a trailing
    comment: occurrence bounds the brackets and a list attribute do not
    convey, a hole's reason, the tables' marks, Wireshark's spelling. A
    member with no identity (a hole, `* [ AVP ]`) is a comment in its
    place; the library keeps such AVPs in the additional AVPs.
    """
    library = resolver.library
    notes = notes or [None] * len(members)
    grouped: dict[Identity, list[model.Member]] = {}
    for member, target in members:
        if target is not None and target.identity is not None:
            grouped.setdefault(target.identity, []).append(member)
    used: dict[str, int] = {}
    entries = []
    for (member, target), note in zip(members, notes, strict=True):
        if target is None or target.identity is None:
            reason = "" if target is None else f"  # hole: {target.hole}"
            entries.append(Entry(None, f"# {spelled(member)}{reason}"))
            continue
        alike = grouped[target.identity]
        if alike[0] is not member:
            continue
        repeated = len(alike) > 1 or any(m.max_occurs != 1 for m in alike)
        required = any(m.min_occurs > 0 for m in alike)
        attr = library.attributes.get(target.identity) or attribute_name(target.name)
        if attr in RESERVED_ATTRIBUTES:
            attr += "_"
        used[attr] = used.get(attr, 0) + 1
        if used[attr] > 1:
            attr = f"{attr}_{used[attr]}"
        vendor, _ = target.identity
        args = [quoted(attr), resolver.constant(target) or ""]
        if vendor != 0:
            args.append(library.vendors[vendor])
        if required:
            args.append("is_required=True")
        if target.is_mandatory is not None:
            args.append(f"is_mandatory={target.is_mandatory}")
        type_class = resolver.type_class(target)
        if type_class is not None:
            args.append(f"type_class={type_class}")
        comments = []
        if len(alike) > 1:
            comments.append(
                "printed " + " and ".join(spelled(m) for m in alike) + ", one list"
            )
        else:
            # A list attribute and `is_required` convey `[ X ]`, `{ X }`,
            # `*[ X ]` and `1*{ X }`; any other bounds would be lost.
            default_min = 0 if member.rule.presence is ast.Presence.OPTIONAL else 1
            if member.max_occurs not in (1, None) or member.min_occurs != default_min:
                comments.append(spelled(member))
        if target.hole is not None:
            comments.append(f"hole: {target.hole}")
        if note is not None:
            comments.append(note)
        addition = resolver.additions.get(target.identity)
        if addition is not None and addition.replaces is not None:
            comments.append(
                f"additions.py corrects the library's {addition.replaces}"
                f" to {addition.avp_class}"
            )
        if target.wireshark_alias is not None:
            comments.append(f"Wireshark: {target.wireshark_alias}")
        comment = f"  # {'; '.join(comments)}" if comments else ""
        python_type = type_class or PYTHON_TYPE[resolver.avp_class(target)]
        entries.append(
            Entry(
                attr,
                f"AvpGenDef({', '.join(args)}),{comment}",
                python_type,
                repeated,
            )
        )
    return entries


def annotation(entry: Entry) -> str:
    assert entry.python_type is not None
    return f"list[{entry.python_type}]" if entry.repeated else entry.python_type


def application_line(
    application: model.Application, library: Library, registered: str | None = None
) -> str:
    """The module's `APPLICATION_ID`, its comment naming the application as
    the registry does where the document names it nowhere."""
    identifier = application.application_id
    if identifier is None:
        return "APPLICATION_ID = None"
    named = "" if registered is None else f", {registered}"
    constant = library.applications.get(identifier)
    if constant is None:
        return (
            f"APPLICATION_ID = {identifier}  # the library has no APP_ constant{named}"
        )
    return f"APPLICATION_ID = {constant}  # {identifier}{named}"


def render_unit(unit: Unit, resolver: Resolver) -> str:
    library = resolver.library
    application = unit.application
    if application.application_id is None:
        heading = (
            f"{unit.name} commands, clause {application.clause}. The document's"
            " command headers print no application id."
        )
    else:
        named = f" ({application.name})" if application.name else ""
        heading = (
            f"{unit.name} commands, clause {application.clause}, application"
            f" {application.application_id}{named}."
        )
    stated = ""
    if application.stated_in is not None and all(
        message.application_id is None for message in application.messages
    ):
        # The id is the document's statement in prose, not any header's.
        stated = (
            "The command headers print no application id; clause"
            f" {application.stated_in} states {application.name}'s."
        )
    imported: set[str] = set()
    uses_datetime = False
    names = []
    classes: list[str] = []
    for code, (base, base_name) in unit.bases.items():
        directions = [c for c in unit.commands if c.message.command_code == code]
        names.append(base)
        requests = [c for c in directions if c.class_name.endswith("Request")]
        answers = [c for c in directions if c.class_name.endswith("Answer")]
        factory = [
            "    @classmethod",
            "    def type_factory(cls, header: MessageHeader)"
            " -> Type[_AnyMessageType] | None:",
            "        if header.is_request:",
            f"            return {requests[0].class_name if requests else None}",
            f"        return {answers[0].class_name if answers else None}",
        ]
        classes += [
            "",
            "",
            f"class {base}(DefinedMessage):",
            f'    """A {base_name} base message.',
            "",
            *textwrap.wrap(
                f"Its subclasses list the members {unit.name} clause"
                f" {application.clause} gives each direction as python"
                " attributes; `APPLICATION_ID` is the header's application id.",
                79,
                initial_indent="    ",
                subsequent_indent="    ",
                break_on_hyphens=False,
            ),
            '    """',
            f"    code: int = {code}",
            f"    name: str = {quoted(base_name)}",
            "    avp_def: AvpGenType",
            "",
            "    def __post_init__(self):",
            "        self.header.command_code = self.code",
            "        super().__post_init__()",
            "",
            *factory,
        ]
        for command in directions:
            message = command.message
            names.append(command.class_name)
            clauses = ", ".join(command.sections)
            plural = "s" if len(command.sections) > 1 else ""
            direction = "Request" if command.class_name.endswith("Request") else ""
            direction = direction or (
                "Answer" if command.class_name.endswith("Answer") else ""
            )
            spelled_as = f"{base_name}-{direction}"
            printed = (
                ""
                if message.name.lower() == spelled_as.lower()
                else f", printed {message.name}"
            )
            entries = gen_defs(command.members, resolver, command.notes)
            for _, target in command.members:
                imported.update(resolver.imports(target))
            body = [
                "",
                "",
                f"class {command.class_name}({base}):",
                f'    """A {spelled_as} message, clause{plural} {clauses}{printed}."""',
            ]
            for entry in entries:
                if entry.attr is not None:
                    written = annotation(entry)
                    uses_datetime |= "datetime" in written
                    body.append(f"    {entry.attr}: {written}")
            body += ["", "    avp_def: AvpGenType = ("]
            body += [f"        {entry.text}" for entry in entries]
            body += ["    )", "", "    def __post_init__(self):"]
            body.append("        super().__post_init__()")
            request = ast.CommandFlag.REQUEST in message.flags
            if request != (direction == "Request"):
                body.append(
                    "        # As printed: the header's REQ flag disagrees with the"
                    " command's name."
                )
            body.append(f"        self.header.is_request = {request}")
            body.append(
                "        self.header.is_proxyable ="
                f" {ast.CommandFlag.PROXIABLE in message.flags}"
            )
            if ast.CommandFlag.ERROR in message.flags:
                body.append("        self.header.is_error = True")
            lists = [entry.attr for entry in entries if entry.attr and entry.repeated]
            if lists:
                body.append("")
                body += [f'        setattr(self, "{attr}", [])' for attr in lists]
            body += [
                "",
                "        assign_attr_from_defs(self, self._avps)",
                "        self._avps = []",
            ]
            classes += body
    lines = [MARKER, '"""', heading, ""]
    if stated:
        lines += [*textwrap.wrap(stated, 79), ""]
    lines += [
        f"Generated from {unit.title} against python-diameter {library.version}.",
        '"""',
        "from __future__ import annotations",
        "",
    ]
    if uses_datetime:
        lines += ["import datetime", ""]
    lines += [
        "from typing import Type",
        "",
        "from diameter.message._base import Message, MessageHeader,"
        " DefinedMessage, _AnyMessageType",
        "from diameter.message.avp.grouped import *",
        "from diameter.message.avp.generator import AvpGenDef, AvpGenType",
        "from diameter.message.commands._attributes import assign_attr_from_defs",
        "from diameter.message.constants import *",
    ]
    if imported:
        lines.append("")
        lines.append("from .additions import (")
        lines += [f"    {name}," for name in sorted(imported)]
        lines.append(")")
    lines += ["", ""]
    lines.append(f"__all__ = [{', '.join(quoted(name) for name in sorted(names))}]")
    lines += ["", application_line(application, library, unit.registered)]
    lines += classes
    return "\n".join(lines) + "\n"


def _grouped_order(resolver: Resolver) -> list[GroupedAddition]:
    """Grouped additions with every member's class before the class
    naming it, since a dataclass's `avp_def` is read at definition."""
    done: set[int] = set()
    order: list[GroupedAddition] = []

    def visit(definition: Definition) -> None:
        added = resolver.grouped.get(id(definition))
        if added is None or id(definition) in done:
            return
        done.add(id(definition))
        for _, target in definition.members:
            if target is not None:
                visit(target)
        order.append(added)

    for definition in resolver.definitions:
        visit(definition)
    return order


def render_grouped(added: GroupedAddition, resolver: Resolver) -> list[str]:
    definition = added.definition
    identity = definition.identity
    assert identity is not None
    sample = definition.sample
    where = f"{min(definition.documents)}"
    if sample.section is not None:
        where += f" clause {sample.section}"
    why = "; ".join(resolver.gaps(definition))
    entries = gen_defs(definition.members, resolver)
    lines = [
        "",
        "",
        "@dataclasses.dataclass",
        f"class {added.class_name}:",
        f'    """A data container that represents the "{definition.name}"'
        f" ({identity[1]}) grouped AVP.",
        "",
        *textwrap.wrap(
            f"{where}: {why}.",
            79,
            initial_indent="    ",
            subsequent_indent="    ",
            break_on_hyphens=False,
        ),
    ]
    if definition.hole is not None:
        lines.append(f"    Hole: {definition.hole}.")
    lines.append('    """')
    for entry in entries:
        if entry.attr is None:
            continue
        if entry.repeated:
            lines.append(
                f"    {entry.attr}: {annotation(entry)} ="
                " dataclasses.field(default_factory=list)"
            )
        else:
            lines.append(f"    {entry.attr}: {annotation(entry)} = None")
    lines += [
        "    additional_avps: list[Avp] = dataclasses.field(default_factory=list)",
        "",
        "    # noinspection PyDataclass",
    ]
    if entries:
        lines.append("    avp_def: dataclasses.InitVar[AvpGenType] = (")
        lines += [f"        {entry.text}" for entry in entries]
        lines.append("    )")
    else:
        lines.append("    avp_def: dataclasses.InitVar[AvpGenType] = ()")
    return lines


def _enum_constants(addition: Addition, taken: set[str]) -> list[str]:
    """`E_` constants for a new enumerated AVP's values, as `constants.py`
    spells them; the comment naming where a document defines them instead."""
    lines = []
    for definition in addition.readings:
        sample = definition.sample
        if not isinstance(sample, model.Enumerated):
            continue
        if sample.values_source is not None:
            cited = f"{sample.defined_in} clause {sample.section}"
            comment = f"Values: {sample.values_source} ({cited})."
            lines += [f"# {line}" for line in textwrap.wrap(comment, 86)]
        for value in sample.values:
            if not isinstance(value, ast.EnumValue):
                continue
            name = f"E_{constant_case(addition.name)}_{constant_case(value.name)}"
            if name in taken:
                continue
            taken.add(name)
            lines.append(f"{name} = {value.value}")
        break
    return lines


def render_additions(resolver: Resolver, sources: list[str]) -> str:
    library = resolver.library
    additions = sorted(resolver.additions.values(), key=lambda a: a.identity)
    new = [a for a in additions if a.replaces is None]
    corrected = [a for a in additions if a.replaces is not None]
    grouped = _grouped_order(resolver)
    classes = sorted({a.avp_class for a in additions if a.avp_class != "Avp"} | {"Avp"})
    lines = [
        MARKER,
        '"""',
        "What the generated command modules need beyond python-diameter"
        f" {library.version},",
        "in the library's own shapes, for a maintainer to merge.",
        "",
        "`AVP_DICTIONARY_ADDITIONS` and `AVP_VENDOR_DICTIONARY_ADDITIONS` are",
        "entries `diameter/message/avp/dictionary.py` lacks, keyed by the new",
        "`AVP_*` constants above them; `AVP_DICTIONARY_CORRECTIONS` and",
        "`AVP_VENDOR_DICTIONARY_CORRECTIONS` replace entries it holds with a value",
        "class the specification does not give. The dataclasses are",
        "`diameter/message/avp/grouped.py` classes for grouped AVPs the library has",
        "none for, or whose class lacks members the specification names.",
        "",
        "Importing this module changes nothing in the library. `register()` adds",
        "the new entries to the library's dictionaries, which the command modules",
        "need to encode the AVPs they name; `register(corrections=True)` also",
        "replaces the corrected ones, which changes how the library's own",
        "classes read those AVPs.",
        "",
        "Generated from:",
        "",
        *(f"- {source}" for source in sources),
        '"""',
        "from __future__ import annotations",
        "",
        "import dataclasses",
        "import datetime",
        "",
        "from diameter.message.avp import (",
        *(f"    {name}," for name in classes),
        ")",
        "from diameter.message.avp.dictionary import AVP_DICTIONARY,"
        " AVP_VENDOR_DICTIONARY, AvpInfo",
        "from diameter.message.avp.generator import AvpGenDef, AvpGenType",
        "from diameter.message.avp.grouped import *",
        "from diameter.message.constants import *",
        "",
        "",
    ]
    exported = [a.constant for a in new] + [g.class_name for g in grouped]
    exported += ADDITIONS_NAMES
    lines.append("__all__ = [")
    lines += [f"    {quoted(name)}," for name in exported]
    lines += ["]", ""]
    taken = set(library.names) | {a.constant for a in new}
    for addition in new:
        where = _where(addition)
        lines.append(f"{addition.constant} = {addition.identity[1]}  # {where}")
    enums = [line for a in new for line in _enum_constants(a, taken)]
    if enums:
        lines += ["", *enums]
    for added in grouped:
        lines += render_grouped(added, resolver)
    lines += ["", ""]
    lines += _dictionaries("ADDITIONS", new)
    lines += [""]
    lines += _dictionaries("CORRECTIONS", corrected)
    if resolver.kept:
        lines += [
            "",
            "# Not corrected: the documents disagree, and the library's entry"
            " carries one",
            "# of them.",
        ]
        lines += [f"# - {note}" for note in resolver.kept]
    lines += [
        "",
        "",
        "def register(corrections: bool = False) -> None:",
        '    """Merge the new entries, and with `corrections` the corrected ones,',
        '    into the library\'s global AVP dictionaries."""',
        "    merged = [(AVP_DICTIONARY_ADDITIONS, AVP_VENDOR_DICTIONARY_ADDITIONS)]",
        "    if corrections:",
        "        merged.append(",
        "            (AVP_DICTIONARY_CORRECTIONS, AVP_VENDOR_DICTIONARY_CORRECTIONS))",
        "    for base, vendors in merged:",
        "        AVP_DICTIONARY.update(base)",
        "        for vendor, entries in vendors.items():",
        "            AVP_VENDOR_DICTIONARY.setdefault(vendor, {}).update(entries)",
    ]
    return "\n".join(lines) + "\n"


def _where(addition: Addition) -> str:
    first = addition.readings[0]
    where = min(first.documents)
    if first.sample.section is not None:
        where += f" clause {first.sample.section}"
    return where


def _dictionaries(kind: str, additions: list[Addition]) -> list[str]:
    """The two dictionaries of one kind, one entry per line as
    `dictionary.py` writes them, each with its source and notes."""

    def entry(addition: Addition) -> str:
        vendor, _ = addition.identity
        parts = [f'"name": {quoted(addition.name)}', f'"type": {addition.avp_class}']
        if addition.mandatory:
            parts.append('"mandatory": True')
        if vendor:
            parts.append(f'"vendor": {vendor}')
        notes = [_where(addition)]
        if addition.replaces is not None:
            notes.append(f"the library holds it as {addition.replaces}")
        notes += addition.notes
        for reading in addition.readings:
            if reading.hole is not None:
                notes.append(f"hole: {reading.hole}")
            if reading.wireshark_alias is not None:
                notes.append(f"Wireshark: {reading.wireshark_alias}")
        notes = list(dict.fromkeys(notes))
        return f"    {addition.constant}: {{{', '.join(parts)}}},  # {'; '.join(notes)}"

    base = [a for a in additions if a.identity[0] == 0]
    lines = [f"AVP_DICTIONARY_{kind}: dict[int, AvpInfo] = {{"]
    lines += [entry(a) for a in base]
    lines.append("}")
    lines.append(f"AVP_VENDOR_DICTIONARY_{kind}: dict[int, dict[int, AvpInfo]] = {{}}")
    vendors = sorted({a.identity[0] for a in additions} - {0})
    for vendor in vendors:
        lines.append(f"AVP_VENDOR_DICTIONARY_{kind}[{vendor}] = {{")
        lines += [entry(a) for a in additions if a.identity[0] == vendor]
        lines.append("}")
    return lines


def render_init(
    units: list[Unit], sources: list[str], counts: dict[str, int], version: str
) -> str:
    lines = [
        MARKER,
        '"""Diameter commands per application and interface, in python-diameter',
        f"{version}'s shape, with what its dictionary lacks in `additions`.",
        "",
        "Generated from:",
        "",
        *(f"- {source}" for source in sources),
        "",
        "Modules:",
        "",
    ]
    for unit in units:
        application = unit.application
        what = (
            "no application id"
            if application.application_id is None
            else f"application {application.application_id}"
        )
        if application.name is not None:
            what += f" ({application.name})"
        needs = counts[unit.module]
        lines.append(
            f"- `{unit.module}`: {unit.name} clause {application.clause}, {what};"
            f" {needs} addition{'' if needs == 1 else 's'}"
        )
    lines.append('"""')
    lines.append("")
    modules = ["additions", *(unit.module for unit in units)]
    lines.append(f"__all__ = [{', '.join(quoted(m) for m in modules)}]")
    return "\n".join(lines) + "\n"


