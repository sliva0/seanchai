# The first line of every generated file. A directory holding nothing else
# is one this script may overwrite.
MARKER = "# Generated by Seanchaí (integrations/python_diameter/generate.py)."
LINE_LENGTH = 88

# The library's value classes. DiameterIdentity rides in AvpOctetString and
# DiameterURI in AvpUtf8String because that is how the library's dictionary
# holds Origin-Host and Redirect-Host; the filter-rule types are octets.
AVP_CLASS = {
    ast.DataType.OCTET_STRING: "AvpOctetString",
    ast.DataType.UTF8_STRING: "AvpUtf8String",
    ast.DataType.INTEGER32: "AvpInteger32",
    ast.DataType.INTEGER64: "AvpInteger64",
    ast.DataType.UNSIGNED32: "AvpUnsigned32",
    ast.DataType.UNSIGNED64: "AvpUnsigned64",
    ast.DataType.FLOAT32: "AvpFloat32",
    ast.DataType.FLOAT64: "AvpFloat64",
    ast.DataType.GROUPED: "AvpGrouped",
    ast.DataType.ENUMERATED: "AvpEnumerated",
    ast.DataType.TIME: "AvpTime",
    ast.DataType.ADDRESS: "AvpAddress",
    ast.DataType.DIAMETER_IDENTITY: "AvpOctetString",
    ast.DataType.DIAMETER_URI: "AvpUtf8String",
    ast.DataType.IP_FILTER_RULE: "AvpOctetString",
    ast.DataType.QOS_FILTER_RULE: "AvpOctetString",
}
# The Python value each class decodes to, for the attribute annotations.
PYTHON_TYPE = {
    "AvpOctetString": "bytes",
    "AvpUtf8String": "str",
    "AvpInteger32": "int",
    "AvpInteger64": "int",
    "AvpUnsigned32": "int",
    "AvpUnsigned64": "int",
    "AvpFloat32": "float",
    "AvpFloat64": "float",
    "AvpGrouped": "Grouped",
    "AvpEnumerated": "int",
    "AvpTime": "datetime.datetime",
    "AvpAddress": "str",
}
PRESENCE = {
    ast.Presence.FIXED: "FIXED",
    ast.Presence.REQUIRED: "REQUIRED",
    ast.Presence.OPTIONAL: "OPTIONAL",
}
# Attributes the library's `Message` and `ProtocolMessage`, or a grouped
# value class, already use; an AVP spelled like one gets a trailing
# underscore instead.
RESERVED_ATTRIBUTES = frozenset(
    {
        "additional_avps",
        "application_id",
        "avp_def",
        "avp_rules",
        "avps",
        "code",
        "header",
        "is_error",
        "is_proxyable",
        "is_request",
        "name",
    }
)
# Names `avps.py` binds besides AVPs.
AVPS_MODULE_NAMES = frozenset({"BY_IDENTITY", "BY_WIRESHARK_NAME", "HOLES"})


def attribute_name(avp_name: str) -> str:
    """`_base.attribute_name`, which the runtime derives attributes with;
    the annotations written here must agree with it."""
    name = avp_name.lower().replace("-", "_")
    if name.startswith("3gpp"):
        name = "tgpp" + name.removeprefix("3gpp")
    elif name[0].isdigit():
        name = "avp_" + name
    return name + "_" if keyword.iskeyword(name) else name


def class_name(command_name: str) -> str:
    """`User-Authorization-Request` → `UserAuthorizationRequest`, and
    `Send-Routing-info-for-SM-Answer` the same as its request's
    `Send-Routing-Info-for-SM`: one capitalised word per hyphenated part,
    the way the library writes `OcOlr` and `Mip6AgentInfo`."""
    return "".join(part.capitalize() for part in re.split(r"[-_]", command_name))


def slug(reference: str) -> str:
    """`TS29.229` → `ts29_229`; `RFC6733` → `rfc6733`."""
    return reference.lower().replace(".", "_")


def reference_of(argument: str) -> str:
    """The corpus reference the argument names: `TS29.229`, `29.229`, or a
    full title like `3GPP TS 29.229`, all spelling the same document."""
    if re.fullmatch(r"\d{2}\.\d{3}", argument):
        return f"TS{argument}"
    try:
        return ast.spec_ref(argument)
    except ast.SpecRefError:
        return argument


# --- collecting --------------------------------------------------------------


def _flags(flag_rules: ast.AvpFlagRules | None) -> tuple[str, str, str, str] | None:
    if flag_rules is None:
        return None
    order = list(ast.AvpFlag)

    def letters(flags: frozenset[ast.AvpFlag]) -> str:
        return "".join(flag.value for flag in sorted(flags, key=order.index))

    return (
        letters(flag_rules.must),
        letters(flag_rules.may),
        letters(flag_rules.should_not),
        letters(flag_rules.must_not),
    )


@dataclass(eq=False)
class Definition:
    """One distinct AVP reading the generated set reaches: a complete `Avp`,
    a `Hole` with an identity (an `AvpDef` with `hole` set), or a hole with
    none (an `AvpHole`)."""

    sample: model.Avp | model.Hole
    # Each member's target; None for the `* [ AVP ]` wildcard.
    members: list[tuple[model.Member, Definition | None]]
    documents: set[str] = field(default_factory=set)
    identifier: str = ""

    @property
    def name(self) -> str:
        return self.sample.name

    @property
    def identity(self) -> tuple[int, int] | None:
        sample = self.sample
        if sample.vendor_id is None or sample.code is None:
            return None
        return (sample.vendor_id, sample.code)

    @property
    def avp_class(self) -> str | None:
        data_type = self.sample.data_type
        return None if data_type is None else AVP_CLASS[data_type]

    @property
    def hole(self) -> str | None:
        return str(self.sample) if isinstance(self.sample, model.Hole) else None

    @property
    def wireshark_alias(self) -> str | None:
        """Wireshark's name where it is not the document's spelling."""
        wireshark_name = self.sample.wireshark_name
        return None if wireshark_name == self.name else wireshark_name

    @property
    def python_type(self) -> str:
        avp_class = self.avp_class
        return "Any" if avp_class is None else PYTHON_TYPE[avp_class]


def _body_signature(members: list[tuple[model.Member, Definition | None]]) -> tuple:
    return tuple(
        (
            member.rule.presence,
            member.min_occurs,
            member.max_occurs,
            None if target is None else id(target),
        )
        for member, target in members
    )


class Definitions:
    """Every distinct reading, deduplicated on what goes on the wire.

    Two readings are one definition when name, identity, type, flag rules,
    members and values agree, whichever documents print them: TS 29.329
    re-prints TS 29.229's `Public-Identity`, and one `AvpDef` serves both.
    Where they differ — RFC 8506 dropping the P flag RFC 4006 allows, TS
    29.272 extending TS 29.212's `Allocation-Retention-Priority` — each
    reading is its own definition, and each command's rules name its
    document's.
    """

    def __init__(self) -> None:
        self._by_signature: dict[tuple, Definition] = {}
        # Readings already seen, by object identity: an `Avp` hashes its
        # whole member tree, and the same objects come back for every body
        # naming them. `_seen` keeps them alive so no id is reused.
        self._memo: dict[int, Definition] = {}
        self._seen: list[object] = []

    def __iter__(self):
        return iter(self._by_signature.values())

    def add(self, found: model.Avp | model.Hole) -> Definition:
        known = self._memo.get(id(found))
        if known is not None:
            return known
        members = []
        if isinstance(found, model.Grouped):
            members = [(member, self.member(member)) for member in found.members]
        signature = self._signature(found, members)
        definition = self._by_signature.get(signature)
        if definition is None:
            definition = Definition(found, members)
            self._by_signature[signature] = definition
        definition.documents.add(
            found.defined_in if isinstance(found, model.Avp) else found.reference
        )
        self._memo[id(found)] = definition
        self._seen.append(found)
        return definition

    def member(self, member: model.Member) -> Definition | None:
        """The definition a body line points at; None for the wildcard."""
        if member.avp is not None:
            return self.add(member.avp)
        if member.hole is not None:
            return self.add(member.hole)
        if member.name == "AVP":
            return None
        # A grouped AVP among its own descendants: the model stops there
        # rather than recurse, and the name stays a hole here.
        return self.add(model.Hole("", member.name, (model.DEFINITION,)))

    @staticmethod
    def _signature(
        found: model.Avp | model.Hole,
        members: list[tuple[model.Member, Definition | None]],
    ) -> tuple:
        flags = _flags(found.flag_rules)
        if isinstance(found, model.Hole):
            return ("hole", str(found), found.vendor_id, found.code, found.data_type)
        values = tuple(
            (value.name, value.value)
            if isinstance(value, ast.EnumValue)
            else (value.first, value.last)
            for value in getattr(found, "values", ())
        )
        return (
            found.name,
            found.identity,
            found.data_type,
            flags,
            _body_signature(members),
            values,
        )

    def name(self) -> None:
        """Give every definition a module-level identifier.

        The AVP's name in constant case, unless two definitions would share
        it — two readings of one AVP, or two AVPs spelled alike in different
        vendor spaces — when each takes its first defining document as a
        suffix (`SUBSCRIPTION_ID__RFC4006`), and a counter after that.
        """
        by_base: dict[str, list[Definition]] = {}
        for definition in self:
            base = attribute_name(definition.name).rstrip("_").upper()
            by_base.setdefault(base, []).append(definition)
        for base, sharing in by_base.items():
            if len(sharing) == 1 and base not in AVPS_MODULE_NAMES:
                sharing[0].identifier = base
                continue
            by_document: dict[str, list[Definition]] = {}
            for definition in sharing:
                document = slug(min(definition.documents) or "unresolved").upper()
                by_document.setdefault(f"{base}__{document}", []).append(definition)
            for identifier, alike in by_document.items():
                if len(alike) == 1:
                    alike[0].identifier = identifier
                    continue
                alike.sort(key=_tie_order)
                for number, definition in enumerate(alike, start=1):
                    definition.identifier = f"{identifier}_{number}"


def _tie_order(definition: Definition) -> tuple:
    """An order for readings alike in name and document that does not
    depend on hashing: identity, flags, hole, then the members' names."""
    return (
        definition.identity or (-1, -1),
        _flags(definition.sample.flag_rules) or (),
        definition.hole or "",
        [(member.rule.presence.value, member.name) for member, _ in definition.members],
    )


@dataclass
class Command:
    """One generated Request or Answer class."""

    message: model.Message
    members: list[tuple[model.Member, Definition | None]]
    class_name: str
    # The clauses printing this body; more than one where a document
    # repeats a command identically per procedure (TS 29.273's STa STR).
    sections: list[str]


@dataclass
class Unit:
    """One generated module: one application on one interface."""

    module: str
    application: model.Application
    # "3GPP TS 29.229 V18.1.0", the copy generated from.
    title: str
    # Base class name per command code, in first-appearance order.
    bases: dict[int, tuple[str, str]]
    commands: list[Command]

    @property
    def name(self) -> str:
        """The document's name without its version: "3GPP TS 29.229"."""
        return self.title.split(" V")[0]


def module_names(applications: tuple[model.Application, ...]) -> list[str]:
    """`ts29_229` for a document with one application; the interface clause
    appended where a document has several (`ts29_212_5a`), and the
    application id where several share one clause (`ts29_272_16777308`)."""
    clauses = {application.clause for application in applications}
    per_clause: dict[str, int] = {}
    for application in applications:
        per_clause[application.clause] = per_clause.get(application.clause, 0) + 1
    names = []
    for application in applications:
        parts = [slug(application.reference)]
        if len(clauses) > 1:
            parts.append(application.clause.lower().replace(".", "_"))
        if per_clause[application.clause] > 1:
            parts.append(str(application.application_id))
        names.append("_".join(parts))
    return names


def command_base(name: str) -> str:
    for suffix in ("-Request", "-Answer"):
        if name.lower().endswith(suffix.lower()):
            return name[: -len(suffix)]
    return name


def collect_unit(
    application: model.Application, module: str, title: str, definitions: Definitions
) -> Unit:
    bases: dict[int, tuple[str, str]] = {}
    commands: list[Command] = []
    by_name: dict[str, list[Command]] = {}
    for message in application.messages:
        base = command_base(message.name)
        bases.setdefault(message.command_code, (class_name(base), base))
        members = [(member, definitions.member(member)) for member in message.avps]
        name = class_name(message.name)
        alike = by_name.setdefault(name, [])
        same = [
            command
            for command in alike
            if _body_signature(command.members) == _body_signature(members)
            and command.message.flags == message.flags
        ]
        if same:
            same[0].sections.append(message.section)
            continue
        if alike:
            # The same command printed twice with different bodies (TS
            # 29.273's AAR in clauses 9.2.2.2.1 and 9.2.2.5.1): the later
            # copy keeps its clause in its name.
            name = f"{name}_{message.section.replace('.', '_')}"
        command = Command(message, members, name, [message.section])
        alike.append(command)
        commands.append(command)
    return Unit(module, application, title, bases, commands)


