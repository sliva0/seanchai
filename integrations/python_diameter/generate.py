@dataclass
class Library:
    """What the installed python-diameter already defines, read off its
    modules: the generated code references these names instead of
    restating them."""

    version: str
    # The global dictionary, keyed by identity like `get_avp_dictionary_entry`.
    entries: dict[Identity, dict]
    # The `AVP_*` constant `dictionary.py` keys each entry with.
    constants: dict[Identity, str]
    # Every identity the dictionary holds under a name, for saying where it
    # holds an AVP the document places elsewhere.
    by_name: dict[str, list[Identity]]
    # Every name `constants.py` and `grouped.py` bind, so an addition never
    # shadows one.
    names: set[str]
    vendors: dict[int, str]
    applications: dict[int, str]
    # Command code → (base class name, command name), as `all_commands` has it.
    commands: dict[int, tuple[str, str]]
    # Identity → the grouped dataclass the library decodes it into.
    grouped: dict[Identity, type]
    # Identity → the attribute every `avp_def` the library writes names it
    # with, where they all agree.
    attributes: dict[Identity, str]

    @classmethod
    def load(cls) -> Library:
        import diameter.message.avp.dictionary as dictionary
        import diameter.message.avp.grouped as grouped
        import diameter.message.commands as commands
        from diameter.message import constants
        from diameter.message._base import DefinedMessage, Message, UndefinedMessage
        from diameter.message.avp.generator import AvpGenDef

        entries: dict[Identity, dict] = {
            (0, code): info for code, info in dictionary.AVP_DICTIONARY.items()
        }
        for vendor, table in dictionary.AVP_VENDOR_DICTIONARY.items():
            if vendor != 0:
                entries.update({(vendor, code): info for code, info in table.items()})
        # The entries' keys are constants, which the runtime dictionary has
        # already turned into numbers; the source still names them.
        keyed: dict[Identity, str] = {}
        for node in python_ast.parse(inspect.getsource(dictionary)).body:
            if isinstance(node, python_ast.AnnAssign | python_ast.Assign):
                target = (
                    node.target
                    if isinstance(node, python_ast.AnnAssign)
                    else node.targets[0]
                )
                vendor = None
                if isinstance(target, python_ast.Name):
                    vendor = 0 if target.id == "AVP_DICTIONARY" else None
                elif (
                    isinstance(target, python_ast.Subscript)
                    and isinstance(target.value, python_ast.Name)
                    and target.value.id == "AVP_VENDOR_DICTIONARY"
                    and isinstance(target.slice, python_ast.Constant)
                ):
                    vendor = target.slice.value
                if vendor is None or not isinstance(node.value, python_ast.Dict):
                    continue
                for key in node.value.keys:
                    if isinstance(key, python_ast.Name):
                        keyed[(vendor, getattr(constants, key.id))] = key.id
        by_name: dict[str, list[Identity]] = {}
        for identity, info in sorted(entries.items()):
            by_name.setdefault(info["name"], []).append(identity)
        bound = vars(constants)
        vendors: dict[int, str] = {}
        applications: dict[int, str] = {}
        for name, value in bound.items():
            if name.startswith("VENDOR_") and isinstance(value, int):
                vendors.setdefault(value, name)
            elif name.startswith("APP_") and isinstance(value, int):
                applications.setdefault(value, name)
        named = {
            code: (command.__name__, command.name)
            for code, command in commands.all_commands.items()
            if command not in (Message, DefinedMessage, UndefinedMessage)
        }
        holders = [getattr(grouped, name) for name in grouped.__all__]
        holders += [
            subclass
            for code in named
            for subclass in commands.all_commands[code].__subclasses__()
        ]
        uses: dict[Identity, set[type]] = {}
        spellings: dict[Identity, set[str]] = {}
        for holder in holders:
            for definition in getattr(holder, "avp_def", ()) or ():
                if not isinstance(definition, AvpGenDef):
                    continue
                identity = (definition.vendor_id, definition.avp_code)
                spellings.setdefault(identity, set()).add(definition.attr_name)
                if definition.type_class is not None:
                    uses.setdefault(identity, set()).add(definition.type_class)
        classes: dict[Identity, type] = {}
        # A grouped class's docstring names the AVP it holds; that wins over
        # the uses, one of which (0.9.0's `AocInformation` for code 2314) is
        # the wrong class.
        for holder in holders[: len(grouped.__all__)]:
            found = re.search(r'"([^"]+)" \((\d+)\)', holder.__doc__ or "")
            if found is None:
                continue
            for identity in by_name.get(found.group(1), ()):
                if identity[1] == int(found.group(2)):
                    classes.setdefault(identity, holder)
        for identity, used in uses.items():
            if identity not in classes:
                classes[identity] = min(used, key=lambda used: used.__name__)
        # A key the source parse missed would leave an entry with no
        # constant to reference.
        assert set(keyed) >= set(entries), set(entries) - set(keyed)
        return cls(
            version=importlib.metadata.version("python-diameter"),
            entries=entries,
            constants=keyed,
            by_name=by_name,
            names={name for name in bound if not name.startswith("_")}
            | set(grouped.__all__),
            vendors=vendors,
            applications=applications,
            commands=named,
            grouped=classes,
            attributes={
                identity: next(iter(names))
                for identity, names in spellings.items()
                if len(names) == 1
            },
        )

    def members(self, holder: type) -> dict[Identity, tuple[type | None, bool]]:
        """A library grouped class's members, each with its own class and
        the M bit it encodes with: its `is_mandatory`, or where that is
        None, the dictionary entry's default, as `Avp.new` reads it."""
        members = {}
        for definition in getattr(holder, "avp_def", ()) or ():
            identity = (definition.vendor_id, definition.avp_code)
            mandatory = definition.is_mandatory
            if mandatory is None:
                mandatory = bool(self.entries.get(identity, {}).get("mandatory"))
            members[identity] = (definition.type_class, mandatory)
        return members


