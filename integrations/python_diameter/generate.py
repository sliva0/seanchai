type Identity = tuple[int, int]


def attribute_name(avp_name: str) -> str:
    """The instance attribute an AVP's value lives in, where the library
    does not already spell one: `Session-Id` is `session_id`. A leading
    `3GPP` reads `tgpp`, as the library writes `tgpp_imsi`, and any other
    leading digit gets an `avp_` prefix."""
    name = re.sub(r"[^0-9a-z]+", "_", avp_name.lower()).strip("_")
    if name.startswith("3gpp"):
        name = "tgpp" + name.removeprefix("3gpp")
    elif name[0].isdigit():
        name = "avp_" + name
    return name + "_" if keyword.iskeyword(name) else name


def constant_case(text: str) -> str:
    """`3GPP-IMSI` → `3GPP_IMSI`, the library's constant spelling."""
    return re.sub(r"[^0-9A-Za-z]+", "_", text).strip("_").upper()


def class_name(name: str) -> str:
    """`User-Authorization-Request` → `UserAuthorizationRequest`: one
    capitalised word per hyphenated part, the way the library writes `OcOlr`
    and `Mip6AgentInfo`. A leading `3GPP` reads `Tgpp`, as attributes read
    `tgpp`, and any other leading digit gets an `Avp` prefix."""
    spelled = "".join(part.capitalize() for part in re.split(r"[^0-9A-Za-z]+", name))
    if spelled.startswith("3gpp"):
        return "Tgpp" + spelled.removeprefix("3gpp")
    return "Avp" + spelled if spelled[0].isdigit() else spelled


def slug(reference: str) -> str:
    """`TS29.229` → `ts29_229`; `RFC6733` → `rfc6733`; `ETSI-ES283.034` →
    `etsi_es283_034`, an identifier the `import` statement takes."""
    return reference.lower().replace(".", "_").replace("-", "_")


def reference_of(argument: str) -> str:
    """The corpus reference the argument names: `TS29.229`, `29.229`, or a
    full title like `3GPP TS 29.229`, all spelling the same document."""
    if re.fullmatch(r"\d{2}\.\d{3}", argument):
        return f"TS{argument}"
    try:
        return ast.spec_ref(argument)
    except ast.SpecRefError:
        return argument


def quoted(text: str) -> str:
    """A double-quoted literal, the library's quoting."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def spelled(member: model.Member) -> str:
    """The member's ABNF line as the document prints it: `*2 [ X ]`."""
    rule = member.rule
    opening, closing = abnf.brackets_for(rule.presence)
    qualifier = abnf.qualifier(rule.min_occurs, rule.max_occurs)
    return f"{qualifier} {opening} {rule.name} {closing}".strip()


