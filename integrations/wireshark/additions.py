#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.14"
# dependencies = ["seanchai"]
#
# [tool.uv.sources]
# seanchai = { path = "../..", editable = true }
# ///
"""Stage Wireshark dictionary patches adding the AVPs the oracle finds absent.

`seanchai crosscheck` reports, per file, the AVPs Wireshark's dictionary has
no entry for at their `(vendor-id, code)`. This writes one `git format-patch`
file per defining document, each adding that document's absent AVPs to the
pinned dictionary in its own XML shape: name, code, vendor, the type (an
`<enum>` per value of an enumerated AVP, a `<gavp>` per member of a grouped
one) and the M and V bits from the flag rules.

    uv run integrations/wireshark/additions.py
    uv run integrations/wireshark/additions.py --dictionary DIR --corpus DIR \\
        -o integrations/wireshark/additions

An entry goes after the dictionary entry of its vendor with the nearest
lower code, preferring an entry its own document defines, so it lands
beside its siblings in whichever file holds them, and before the nearest
higher one when there is no lower. Every patch applies on its own to the
pinned tree and all of them in order. The output is a function of the
corpus and the pinned dictionary alone, byte for byte; the author and date
are fixed arguments.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
from collections.abc import Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from seanchai import corpus, model, oracle
from seanchai.dad import ast

_ROOT = Path(__file__).resolve().parent.parent.parent
_TREE = Path("resources/protocols/diameter")
# The first line of every generated patch's description says what wrote it,
# so an output directory holding nothing else is one this script may replace.
_MARKER = "Generated by Seanchaí (integrations/wireshark/additions.py)."

# Wireshark's typedefn per corpus type; Grouped is a <grouped> element.
# Address is written `IPAddress`, as the dictionary writes RFC 6733's own
# Host-IP-Address, so the dissector shows the address.
_TYPE_NAMES = {
    ast.DataType.OCTET_STRING: "OctetString",
    ast.DataType.UTF8_STRING: "UTF8String",
    ast.DataType.INTEGER32: "Integer32",
    ast.DataType.INTEGER64: "Integer64",
    ast.DataType.UNSIGNED32: "Unsigned32",
    ast.DataType.UNSIGNED64: "Unsigned64",
    ast.DataType.FLOAT32: "Float32",
    ast.DataType.FLOAT64: "Float64",
    ast.DataType.ENUMERATED: "Enumerated",
    ast.DataType.ADDRESS: "IPAddress",
    ast.DataType.TIME: "Time",
    ast.DataType.DIAMETER_IDENTITY: "DiameterIdentity",
    ast.DataType.DIAMETER_URI: "DiameterURI",
    ast.DataType.IP_FILTER_RULE: "IPFilterRule",
    ast.DataType.QOS_FILTER_RULE: "QoSFilterRule",
}
# An <avp>'s flag attributes, by the column the flag rules place the bit in.
_FLAG_VALUES = (
    ("must", "must"),
    ("may", "may"),
    ("should_not", "shouldnot"),
    ("must_not", "mustnot"),
)
_AVP_RE = re.compile(r"^(?P<indent>[ \t]*)<avp\s[^>]*>", re.MULTILINE)
_ATTRIBUTE_RE = re.compile(r'(?P<key>[\w-]+)\s*=\s*"(?P<value>[^"]*)"')


@dataclass(frozen=True)
class Addition:
    """One absent AVP, as the document defining it states it."""

    reference: str
    name: str
    vendor: int
    code: int
    data_type: ast.DataType
    flag_rules: ast.AvpFlagRules | None
    may_encrypt: bool | None
    where: str
    members: tuple[str, ...] = ()
    values: tuple[ast.EnumValue, ...] = ()
    # The `; Values:` citation where the clause points elsewhere for its
    # values: those listed are the cited document's, supplied by a
    # correction (TS 29.272's from TS 32.422).
    values_source: str | None = None


@dataclass(frozen=True)
class Skipped:
    reference: str
    name: str
    why: str
    # Named like another entry, rather than incomplete.
    clash: bool = False


@dataclass(frozen=True)
class Entry:
    """One `<avp>` element of the pinned dictionary, where it sits."""

    file: str
    name: str
    vendor: int
    code: int
    start: int  # offset of the line opening it
    end: int  # offset just past the line closing it
    indent: str
    lines: tuple[int, int]  # line numbers of `start` and `end`


@dataclass
class Document:
    """One defining document's additions, and the patch adding them."""

    reference: str
    specification: ast.Specification
    additions: list[Addition]
    skipped: list[Skipped] = field(default_factory=list)


def _document_title(spec: ast.Specification) -> str:
    version = f" V{spec.version}" if spec.version else ""
    return f"{spec.specification}{version}"


def _where(spec: ast.Specification, name: str, section: str | None) -> str:
    """Where the document states the AVP: its clause, else its table."""
    if section is not None:
        unit = "section" if spec.specification.startswith("RFC") else "clause"
        return f"{unit} {section}"
    for block in spec.sections:
        if isinstance(block, ast.AvpTable) and any(r.name == name for r in block.rows):
            return f"table {block.table}" if block.table else "its AVP table"
    return "its AVP table"


def _definition(
    spec: ast.Specification, name: str
) -> ast.GroupedAvp | ast.EnumeratedAvp | None:
    for block in spec.sections:
        if isinstance(block, ast.GroupedAvp | ast.EnumeratedAvp) and block.name == name:
            return block
    return None


def _first_row(spec: ast.Specification, name: str) -> ast.AvpTableRow | None:
    for block in spec.sections:
        if isinstance(block, ast.AvpTable):
            for row in block.rows:
                if row.name == name:
                    return row
    return None


def _owners(
    books: corpus.Corpus, dictionary: oracle.Oracle
) -> dict[tuple[int, int], tuple[corpus.Entry, oracle.Claim]]:
    """Each absent identity, with the file whose claim defines it: the one
    in the identity's own vendor space where several claim it (TS 29.273
    tabulates RFC 5777's `QoS-Capability`), else the first in corpus
    order."""
    owners: dict[tuple[int, int], tuple[corpus.Entry, oracle.Claim]] = {}
    # The newest copies: an older release held for a citation (TS 32.299
    # V11.20.0) is not what the corpus adds to a dictionary.
    for entry in sorted(books.newest(), key=lambda e: e.path.as_posix()):
        for claim in oracle.claims(entry.spec):
            identity = (claim.vendor, claim.code)
            if identity in dictionary.avps:
                continue
            held = owners.get(identity)
            if held is None or (
                held[0].spec.vendor_id != claim.vendor
                and entry.spec.vendor_id == claim.vendor
            ):
                owners[identity] = (entry, claim)
    return owners


def _addition(
    built: model.Model, entry: corpus.Entry, claim: oracle.Claim
) -> Addition | Skipped:
    reference = entry.reference
    found = built.resolve(reference, claim.name)
    hole = None if found is not None else built.hole(reference, claim.name)
    data_type = found.data_type if found else hole.data_type if hole else None
    if data_type is None:
        return Skipped(reference, claim.name, "the document states no type")
    flag_rules = found.flag_rules if found else hole.flag_rules if hole else None
    section = found.section if found else hole.section if hole else None
    row = _first_row(entry.spec, claim.name)
    definition = _definition(entry.spec, claim.name)
    members: tuple[str, ...] = ()
    values: tuple[ast.EnumValue, ...] = ()
    values_source = None
    if isinstance(definition, ast.GroupedAvp):
        names = dict.fromkeys(r.name for r in definition.avps if r.name != "AVP")
        members = tuple(names)
    if data_type is ast.DataType.GROUPED and not members:
        # The DTD's <grouped> holds one <gavp> or more.
        return Skipped(reference, claim.name, "grouped, with no members stated here")
    elif isinstance(definition, ast.EnumeratedAvp):
        values = tuple(v for v in definition.values if isinstance(v, ast.EnumValue))
        values_source = definition.values_source if values else None
    return Addition(
        reference=reference,
        name=claim.name,
        vendor=claim.vendor,
        code=claim.code,
        data_type=data_type,
        flag_rules=flag_rules,
        may_encrypt=None if row is None else row.may_encrypt,
        where=_where(entry.spec, claim.name, section),
        members=members,
        values=values,
        values_source=values_source,
    )


def _entries(tree: Path, vendors: dict[str, int]) -> list[Entry]:
    entries = []
    for path in sorted(tree.glob("*.xml")):
        text = path.read_text(encoding="utf-8")
        # Commented-out entries are no anchors: TGPP.xml keeps whole
        # alternative sections in comments.
        comments = [m.span() for m in re.finditer(r"<!--.*?-->", text, re.DOTALL)]
        for match in _AVP_RE.finditer(text):
            if any(start < match.start() < end for start, end in comments):
                continue
            attributes = dict(_ATTRIBUTE_RE.findall(match.group()))
            close = text.find("</avp>", match.end())
            self_closing = match.group().endswith("/>")
            end = match.end() if self_closing else close + len("</avp>")
            end = text.find("\n", end) + 1 or len(text)
            entries.append(
                Entry(
                    file=path.name,
                    name=attributes["name"],
                    vendor=vendors.get(attributes.get("vendor-id", "None"), -1),
                    code=int(attributes["code"]),
                    start=match.start(),
                    end=end,
                    indent=match["indent"],
                    lines=(
                        text.count("\n", 0, match.start()),
                        text.count("\n", 0, end),
                    ),
                )
            )
    return entries


def _vendors(tree: Path) -> tuple[dict[str, int], dict[int, str]]:
    text = (tree / "dictionary.xml").read_text(encoding="utf-8")
    symbols = {"None": 0}
    for match in re.finditer(r"<vendor\s[^>]*>", text):
        attributes = dict(_ATTRIBUTE_RE.findall(match.group()))
        symbols[attributes["vendor-id"]] = int(attributes["code"])
    return symbols, {code: symbol for symbol, code in reversed(symbols.items())}


def _anchors(
    addition: Addition, entries: list[Entry], own: set[str]
) -> Iterator[tuple[Entry, bool]]:
    """The entries an addition may go beside, best first, and whether
    after each: the nearest lower codes of its vendor, among its own
    document's entries first, then before the nearest higher ones."""
    same = [e for e in entries if e.vendor == addition.vendor]
    lower = sorted(
        (e for e in same if e.code < addition.code), key=lambda e: (-e.code, e.start)
    )
    yield from ((e, True) for e in lower if e.name in own)
    yield from ((e, True) for e in lower)
    higher = sorted(
        (e for e in same if e.code > addition.code), key=lambda e: (e.code, e.start)
    )
    yield from ((e, False) for e in higher)


# How near another patch's insertion may be: `git format-patch` prints three
# lines of context, and a patch must apply whether or not the others have.
_CONTEXT = 3


def _flag(rules: ast.AvpFlagRules | None, flag: ast.AvpFlag) -> str | None:
    if rules is None:
        return None
    for column, value in _FLAG_VALUES:
        if flag in getattr(rules, column):
            return value
    return None


def _xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _element(
    addition: Addition, indent: str, vendor_symbols: dict[int, str], names: dict
) -> str:
    """The `<avp>` element, in the attribute order the 3GPP entries use."""
    step = "\t" if indent.startswith("\t") else "  "
    attributes = [f'name="{_xml(addition.name)}"', f'code="{addition.code}"']
    mandatory = _flag(addition.flag_rules, ast.AvpFlag.MANDATORY)
    if mandatory is not None:
        attributes.append(f'mandatory="{mandatory}"')
    vendor_bit = _flag(addition.flag_rules, ast.AvpFlag.VENDOR)
    if vendor_bit is None and addition.vendor:
        # RFC 6733 section 4.1: the V bit says the Vendor-ID field is present.
        vendor_bit = "must"
    if vendor_bit is not None:
        attributes.append(f'vendor-bit="{vendor_bit}"')
    if addition.may_encrypt is not None:
        attributes.append(f'may-encrypt="{"yes" if addition.may_encrypt else "no"}"')
    if addition.vendor:
        attributes.append(f'vendor-id="{vendor_symbols[addition.vendor]}"')
    lines = [f"{indent}<avp {' '.join(attributes)}>"]
    inner = indent + step
    if addition.data_type is ast.DataType.GROUPED:
        lines.append(f"{inner}<grouped>")
        lines.extend(
            f'{inner}{step}<gavp name="{_xml(names.get(member, member))}"/>'
            for member in addition.members
        )
        lines.append(f"{inner}</grouped>")
    else:
        lines.append(f'{inner}<type type-name="{_TYPE_NAMES[addition.data_type]}"/>')
        lines.extend(
            f'{inner}<enum name="{_xml(value.name)}" code="{value.value}"/>'
            for value in addition.values
        )
    lines.append(f"{indent}</avp>")
    return "".join(f"{line}\n" for line in lines)


def _fill(text: str) -> str:
    return textwrap.fill(text, 72, break_on_hyphens=False, break_long_words=False)


def _counted(count: int, noun: str) -> str:
    return f"{count} {noun}{'' if count == 1 else 's'}"


def _message(document: Document) -> str:
    """The commit message: the merge request's title and description."""
    spec = document.specification
    additions = document.additions
    title = (
        f"Diameter: Add {additions[0].name} from {spec.specification}"
        if len(additions) == 1
        else f"Diameter: Add {len(additions)} AVPs from {spec.specification}"
    )
    vendor = additions[0].vendor
    space = f"vendor {vendor}" if vendor else "the IETF space"
    one = len(additions) == 1
    intro = (
        f"{_document_title(spec)} defines {'this AVP' if one else 'these AVPs'}"
        f" in {space}, which the dictionary has no entry for at"
        f" {'its code' if one else 'their codes'}:"
    )
    body = [_fill(intro), ""]
    for addition in additions:
        kind = addition.data_type.value
        if addition.values:
            kind += f", {_counted(len(addition.values), 'value')}"
        if addition.members:
            kind += f", {_counted(len(addition.members), 'member')}"
        body.append(f"  {addition.name} ({addition.code}): {kind}, {addition.where}")
    body.append("")
    notes = [
        "Each entry's type, enumerated values and grouped members are the"
        " document's, from its clauses and AVP tables, and so are its M and V"
        " bits where the document states them."
    ]
    cited = [f'{a.name} ("{a.values_source}")' for a in additions if a.values_source]
    if cited:
        listed = ", ".join(cited[:-1]) + " and " if len(cited) > 1 else ""
        notes.append(
            f"The document cites the values of {listed}{cited[-1]} instead of"
            " printing them; those entries carry the cited document's values."
        )
    unstated = [a.name for a in additions if a.flag_rules is None]
    if unstated:
        notes.append(
            f"The document states no flag rules for {', '.join(unstated)}, so"
            " their mandatory attribute is left at the dictionary's default"
            + (
                ", and the V bit follows the Vendor-ID (RFC 6733 section 4.1)."
                if vendor
                else "."
            )
        )
    open_m = [
        a.name
        for a in additions
        if isinstance(a.flag_rules, model.FlagRules)
        and ast.AvpFlag.MANDATORY in a.flag_rules.application_defined
    ]
    if open_m:
        notes.append(
            f"The document states no M bit for {', '.join(open_m)}: RFC 6733"
            " section 4.1 leaves it to the application that uses an AVP, so"
            f" {'its' if len(open_m) == 1 else 'their'} mandatory attribute is"
            " left at the dictionary's default, and section 4.1.1 forbids the"
            " V bit in the IETF space."
        )
    no_m = [
        a.name
        for a in additions
        if a.flag_rules is not None
        and a.name not in open_m
        and _flag(a.flag_rules, ast.AvpFlag.MANDATORY) is None
    ]
    if no_m:
        notes.append(
            f"The document states no M bit for {', '.join(no_m)}, so"
            f" {'its' if len(no_m) == 1 else 'their'} mandatory attribute is"
            " left at the dictionary's default."
        )
    if document.skipped:
        notes.append(
            "Not added here: "
            + "; ".join(f"{skip.name}, {skip.why}" for skip in document.skipped)
            + "."
            + (
                " Wireshark names each display filter field after its AVP,"
                " so two entries named alike need one renamed, as"
                " Cx-User-Data and Sh-User-Data are."
                if any(skip.clash for skip in document.skipped)
                else ""
            )
        )
    for note in notes:
        body.extend([_fill(note), ""])
    body.append(_MARKER)
    return f"{title}\n\n" + "\n".join(body) + "\n"


def _git(tree: Path, *args: str, env: dict | None = None) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=tree,
        check=True,
        capture_output=True,
        text=True,
        env=env,
    ).stdout


def _slug(reference: str) -> str:
    return reference.lower().replace(".", "-")


def _ordered(reference: str) -> tuple[int, str]:
    # 3GPP's documents, then other publishers' (ETSI's TISPAN
    # transcriptions), then the RFCs.
    if reference.startswith("RFC"):
        return (2, reference)
    return (1 if ast.is_external(reference) else 0, reference)


def stage(
    corpus_dir: Path,
    dictionary: Path,
    output: Path,
    author: str,
    date: str,
    defects: Sequence[Path] = (),
) -> tuple[list[Document], list[Skipped]]:
    """Write the patches into `output`, returning what each adds and what
    could not be added."""
    books = corpus.Corpus.load([corpus_dir])
    loaded = oracle.Oracle.load(dictionary)
    built = model.Model.build(books, dictionary=dictionary)
    documents: dict[str, Document] = {}
    skipped: list[Skipped] = []
    books_by_reference = {entry.reference: entry.spec for entry in books.newest()}
    # Every identity holding a name: the dictionary's, then the additions'.
    holders: dict[str, set[tuple[int, int]]] = {}
    for identity, entries in loaded.avps.items():
        for each in entries:
            holders.setdefault(each.name, set()).add(identity)
    made: list[Addition] = []
    _, declared = _vendors(dictionary)
    for (_, _), (entry, claim) in sorted(
        _owners(books, loaded).items(),
        key=lambda item: (item[1][0].reference, item[0][1]),
    ):
        if claim.vendor not in declared:
            # An entry goes beside its vendor's; a vendor the dictionary
            # does not declare (oneM2M's 45687) has no file to go in, and
            # adding one is a vendor file, an entity and a `<vendor>`, not
            # an addition of this series' shape.
            skipped.append(
                Skipped(
                    entry.reference,
                    claim.name,
                    f"vendor {claim.vendor}, which the dictionary declares no"
                    " vendor for",
                )
            )
            continue
        addition = _addition(built, entry, claim)
        if isinstance(addition, Skipped):
            skipped.append(addition)
            continue
        made.append(addition)
        holders.setdefault(addition.name, set()).add((addition.vendor, addition.code))
    added = {(a.vendor, a.code): a.reference for a in made}
    for addition in made:
        others = holders[addition.name] - {(addition.vendor, addition.code)}
        if others:
            # Wireshark keys its display filter fields by name, so two
            # entries spelled alike collide; which one gets another name,
            # as Wireshark's Cx-User-Data and Sh-User-Data do, is the
            # maintainer's call.
            elsewhere = ", ".join(
                f"the dictionary's code {code} of vendor {vendor}"
                if (vendor, code) in loaded.avps
                else f"{added[vendor, code]}'s code {code}"
                for vendor, code in sorted(others)
            )
            skipped.append(
                Skipped(
                    addition.reference,
                    addition.name,
                    f"code {addition.code}, named like {elsewhere}",
                    clash=True,
                )
            )
            continue
        documents.setdefault(
            addition.reference,
            Document(addition.reference, books_by_reference[addition.reference], []),
        ).additions.append(addition)

    for skip in skipped:
        if skip.reference in documents:
            documents[skip.reference].skipped.append(skip)

    with tempfile.TemporaryDirectory() as scratch:
        tree = Path(scratch)
        shutil.copytree(dictionary, tree / _TREE)
        env = {
            **os.environ,
            # The user's configuration would change what format-patch prints.
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_AUTHOR_NAME": author.partition(" <")[0],
            "GIT_AUTHOR_EMAIL": author.partition(" <")[2].rstrip(">"),
            "GIT_COMMITTER_NAME": author.partition(" <")[0],
            "GIT_COMMITTER_EMAIL": author.partition(" <")[2].rstrip(">"),
            "GIT_AUTHOR_DATE": date,
            "GIT_COMMITTER_DATE": date,
        }
        _git(tree, "init", "-q", env=env)
        _git(tree, "add", "-A", env=env)
        _git(tree, "commit", "-q", "-m", "pinned dictionary", env=env)
        base = _git(tree, "rev-parse", "HEAD").strip()
        symbols, vendor_symbols = _vendors(tree / _TREE)
        pinned = _entries(tree / _TREE, symbols)
        # Every addition's name as the dictionary will hold it, so a
        # grouped entry's members name the entries they will be.
        names = {
            member: avp.wireshark_name
            for document in documents.values()
            for addition in document.additions
            for member in addition.members
            if (avp := built.resolve(document.reference, member)) is not None
            and avp.wireshark_name is not None
        }
        # Where each document inserts, per file, by line.
        taken: dict[str, list[tuple[int, str]]] = {}
        for patch in defects:
            for file, line in _touched(patch):
                taken.setdefault(file, []).append((line, patch.name))
        if output.exists():
            for path in output.iterdir():
                if path.suffix != ".patch" or _MARKER not in path.read_text("utf-8"):
                    raise SystemExit(f"{output} holds {path.name}, not written here")
            shutil.rmtree(output)
        output.mkdir(parents=True)
        for number, reference in enumerate(sorted(documents, key=_ordered), 1):
            document = documents[reference]
            own = {
                e.name
                for e in pinned
                if (avp := built.resolve(reference, e.name)) is not None
                and avp.defined_in == reference
            }
            placed: dict[tuple[str, int, bool], list[Addition]] = {}
            for addition in document.additions:
                for anchor, after in _anchors(addition, pinned, own):
                    line = anchor.lines[1] if after else anchor.lines[0]
                    if not any(
                        other != reference and abs(line - at) <= _CONTEXT
                        for at, other in taken.get(anchor.file, ())
                    ):
                        break
                else:
                    raise SystemExit(f"{reference}: no place for {addition.name}")
                taken.setdefault(anchor.file, []).append((line, reference))
                key = (anchor.file, anchor.start, after)
                placed.setdefault(key, []).append(addition)
            _git(tree, "checkout", "-q", "--detach", base)
            texts: dict[str, str] = {}
            # From the end of each file, so earlier offsets stay valid.
            for (file, start, after), group in sorted(placed.items(), reverse=True):
                anchor = next(e for e in pinned if e.file == file and e.start == start)
                text = texts.setdefault(
                    file, (tree / _TREE / file).read_text(encoding="utf-8")
                )
                block = "".join(
                    _element(a, anchor.indent, vendor_symbols, names)
                    for a in sorted(group, key=lambda a: a.code)
                )
                at = anchor.end if after else anchor.start
                texts[file] = text[:at] + block + text[at:]
            for file, text in texts.items():
                (tree / _TREE / file).write_text(text, encoding="utf-8")
            _git(tree, "add", "-A", env=env)
            subprocess.run(
                ["git", "commit", "-q", "-F", "-"],
                cwd=tree,
                input=_message(document),
                text=True,
                check=True,
                env=env,
            )
            patch = _git(
                tree,
                "format-patch",
                "-1",
                "--zero-commit",
                "--no-signature",
                "--stdout",
                env=env,
            )
            (output / f"{number:04d}-{_slug(reference)}.patch").write_text(
                patch, encoding="utf-8"
            )
        _check(tree, base, sorted(output.glob("*.patch")), defects)
    return [documents[r] for r in sorted(documents, key=_ordered)], skipped


def _touched(patch: Path) -> Iterator[tuple[str, int]]:
    """Each line of the pinned tree a patch changes or inserts before, by
    file name and 0-based line number."""
    file, line = "", 0
    for text in patch.read_text(encoding="utf-8").splitlines():
        if text.startswith("+++ b/"):
            file = Path(text.removeprefix("+++ b/")).name
        elif match := re.match(r"@@ -(\d+)", text):
            line = int(match[1]) - 1
        elif not file or text.startswith(("---", "+++")):
            continue
        elif text.startswith("-"):
            yield file, line
            line += 1
        elif text.startswith("+"):
            yield file, line
        elif text.startswith(" "):
            line += 1


def _check(tree: Path, base: str, patches: list[Path], defects: Sequence[Path]) -> None:
    """Every patch applies to the pinned tree on its own, all of them in
    order, and all of them after the defect series."""
    for prefix in ((), defects):
        _git(tree, "checkout", "-q", "--detach", base)
        for patch in prefix:
            _git(tree, "apply", str(patch))
        for patch in patches:
            if not prefix:
                _git(tree, "apply", "--check", str(patch))
        for patch in patches:
            _git(tree, "apply", str(patch))
        _git(tree, "checkout", "-q", "--", ".")


